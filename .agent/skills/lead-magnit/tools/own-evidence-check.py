# ── разбор ::: директив draft.md ──────────────────────────────────────────────

def parse_blocks(text):
    """[{kind, attrs, body(list[str]), line}] по всем ::: директивам верхнего уровня."""
    lines = text.splitlines()
    out = []
    i = 0
    n = len(lines)
    while i < n:
        m = BLOCK_OPEN_RE.match(lines[i].rstrip())
        if m and lines[i].strip() != ":::":
            kind, attrs = m.group(1), m.group(2)
            start = i
            body = []
            i += 1
            while i < n and lines[i].strip() != ":::":
                body.append(lines[i])
                i += 1
            out.append({"kind": kind, "attrs": attrs, "body": body, "line": start + 1})
        i += 1
    return out


