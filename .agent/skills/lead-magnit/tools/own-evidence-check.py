# ── ось «состояние чужого сервиса против парной страницы волны» (r14, по решению автора) ──
#
# 🔴 ДЫРА, которую закрывает эта ось. Гейт сверяет own-блок с НАШИМИ логами и
# на этом останавливается. Если наш лог зафиксировал состояние чужого сервиса
# в 06:40, а соседняя статья ТОЙ ЖЕ волны перезамерила тот же сервис в 08:10 и
# получила другое, гейт остаётся зелёным: число из нашего лога он находит и
# успокаивается. Две взаимно ссылающиеся страницы одного дня расходятся в
# фактах, а машине нечем это увидеть - сверять НАШ лог с логом СОСЕДА она не
# умела вовсе.
#
# Живой случай (guide-neyroset-kandinskiy, круг 12): ячейка сравнения и вывод
# под ней стояли на ночном экране сервиса («лимиты временно сняты», знак
# бесконечности вместо числа), а парная страница волны в логе перезамера прямо
# писала, что это состояние к утру исчезло (флаги hasBanner false, hasInfinity
# false) и что прежний кадр «уже врал пикселями». Читателю давали состояние,
# отменённое в тот же день той же волной.
#
# КАК СУДИМ. Берём цитаты экрана в «ёлочках» внутри own-блока, оставляем те,
# что дословно есть в НАШЕМ логе (значит факт взят из своего замера), и ищем их
# в логах СОСЕДНИХ статей того же рабочего каталога. Совпала строка, а рядом с
# ней в логе соседа стоит опровержение (флаг false, «не было», «уже не»,
# «врал», «исчез») - блок роняется: у волны есть более свежая улика, чем наша.
# Порог длины цитаты высокий (18 знаков после нормализации), окно опровержения
# узкое (строка соседа и по одной соседней) - короткие общие слова осью не
# ловятся, ложных срабатываний на корпусе нет.
CROSS_WAVE_MIN_QUOTE = 18
SCREEN_QUOTE_RE = re.compile(r"[«„]([^«»„“]{6,200})[»“]")
# 🔴 Два класса опровержения, и окна у них РАЗНЫЕ (калибровка на живом корпусе
# по решению автора, ложное срабатывание поймано до внедрения). Машинный флаг
# («… -> false») относится РОВНО к своей строке: в соседней строке лога стоит
# флаг про ДРУГОЙ маркер, и окно ±1 давало ложный дефект на строке «маркер
# «Войти, чтобы создать» -> True», у которой соседом шло «маркер «Создать
# первый кадр» -> False». Прозаическое опровержение («уже не ложится», «врал
# пикселями») наоборот почти никогда не стоит в одной строке с цитатой -
# ему окно ±1 нужно.
FLAG_REFUTATION_RE = re.compile(r"[-=:]>?\s*false\b", re.I)
PROSE_REFUTATION_RE = re.compile(
    r"(?:не\s+было\b|нет\s+вовсе\b|уже\s+не\s+\w+|больше\s+не\s+\w+"
    r"|врал\w*|опроверг\w*|исчез\w*|отменил\w*|отменено\b"
    r"|на\s+экране\s+(?:его|этого)\s+нет)", re.I)


def screen_quotes(text, min_quote):
    """[(как в тексте, нормализованное ядро)] - цитаты экрана в «ёлочках».

    Хвостовая пунктуация с ядра снимается: одна и та же строка экрана в нашем
    тексте стоит с «!» или точкой, а в логе соседа - внутри regex-флага без
    них («hasBanner (/Лимиты на генерацию временно сняты/) -> false»). Без
    снятия хвоста ось не находила бы ровно тот случай, ради которого сделана.
    """
    out = []
    for m in SCREEN_QUOTE_RE.finditer(strip_placeholders(text or "")):
        q = normalize(m.group(1)).strip(" .,!?;:…\"'")
        if len(q) >= min_quote:
            out.append((m.group(1).strip(), q))
    return out


def load_peer_logs(article_dir, max_bytes=8_000_000):
    """Логи СОСЕДНИХ статей волны: {'<слаг соседа>/<файл>': запись лога}.

    Соседи - каталоги того же родителя, у которых есть свой terminal-outputs/.
    Свой каталог исключён. Ограничение по суммарному объёму - чтобы гейт не
    зачитывал корпус целиком на больших рабочих каталогах."""
    out = {}
    art = os.path.abspath(article_dir or "")
    parent = os.path.dirname(art)
    if not art or not os.path.isdir(parent):
        return out
    total = 0
    try:
        names = sorted(os.listdir(parent))
    except OSError:
        return out
    for name in names:
        d = os.path.join(parent, name)
        if not os.path.isdir(d) or os.path.abspath(d) == art:
            continue
        to = os.path.join(d, "terminal-outputs")
        if not os.path.isdir(to):
            continue
        for fname, rec in load_logs(to).items():
            total += len(rec["raw"])
            if total > max_bytes:
                return out
            out[f"{name}/{fname}"] = rec
    return out


def cross_wave_conflicts(text, logs, peer_logs, min_quote=CROSS_WAVE_MIN_QUOTE):
    """[(цитата, файл соседа, строка соседа)] - состояние чужого сервиса,
    взятое из НАШЕГО лога, которое лог парной страницы волны опровергает."""
    if not peer_logs or not logs:
        return []
    ours = " ".join(rec["norm"] for rec in logs.values())
    hits = []
    for raw_q, q in screen_quotes(text, min_quote):
        if q not in ours:
            continue                      # цитата не из нашего замера - не наша ось
        found = None
        for pname, prec in sorted(peer_logs.items()):
            plines = prec["raw"].splitlines()
            for i, ln in enumerate(plines):
                norm_ln = normalize(ln)
                pos = norm_ln.find(q)
                if pos < 0:
                    continue
                # 🔴 на СВОЕЙ строке прозаическое опровержение считается только
                # ПОСЛЕ цитаты («строка «…» уже не показывалась»). Маркер ПЕРЕД
                # цитатой почти всегда относится к другому факту той же фразы -
                # живой случай нашего же лога: «числа 70 на экране не было:
                # висел баннер … и строка «У вас осталось ∞ …»», где «не было»
                # сказано про 70, а цитата стоит как подтверждённая.
                neighbours = " ".join(plines[max(0, i - 1):i]
                                      + plines[i + 1:i + 2])
                tail = norm_ln[pos + len(q):]
                # 🔴 машинный флаг относится к цитате, только если стоит СРАЗУ
                # за ней и между ними не началось новое поле. Иначе строка
                # словаря («… 'vden': 'на сайте можно создать только 60
                # картинок в день', 'banner': false …») роняла бы цитату
                # флагом СОСЕДНЕГО ключа - живой ложный дефект корпуса.
                flag_tail = re.split(r"[,;]", tail, 1)[0]
                if (FLAG_REFUTATION_RE.search(flag_tail)
                        or PROSE_REFUTATION_RE.search(tail)
                        or PROSE_REFUTATION_RE.search(neighbours)):
                    found = (raw_q, pname, ln.strip()[:130])
                    break
            if found:
                break
        if found:
            hits.append(found)
    return hits


def anchor_lines(body_lines, min_len):
    out = []
    for ln in body_lines:
        s = ln.strip()
        if not s or ELLIPSIS_LINE_RE.match(s):
            continue
        norm = normalize(s)
        if len(norm) >= min_len:
            out.append(norm)
    return out


# ── логи terminal-outputs/ ────────────────────────────────────────────────────

def load_logs(to_dir):
    """{filename: {"raw":.., "norm":.., "mtime":.., "embedded_ts": epoch|None}}"""
    logs = {}
    if not to_dir or not os.path.isdir(to_dir):
        return logs
    for name in sorted(os.listdir(to_dir)):
        if not name.lower().endswith((".txt", ".log", ".md")):
            continue
        p = os.path.join(to_dir, name)
        if not os.path.isfile(p):
            continue
        try:
            raw = read(p)
            mtime = os.path.getmtime(p)
        except OSError:
            continue
        logs[name] = {"raw": raw, "norm": normalize(raw), "mtime": mtime,
                      "markers": marker_text(raw),
                      "embedded_ts": extract_embedded_timestamp(raw)}
    return logs


def extract_embedded_timestamp(raw):
    """Первая узнанная самоописанная метка времени внутри лога -> unix-epoch либо None.

    Справочная ось: см. докстринг "чего не ловит". Best-effort, две формы -
    ISO-подобная (2026-08-16 00:44) и unix `date` (Sun Aug 16 08:34:41 +03 2026).
    """
    m = LOG_TIMESTAMP_PATTERNS[0].search(raw)
    if m:
        y, mo, d, h, mi, se = m.groups()
        try:
            return time.mktime((int(y), int(mo), int(d), int(h), int(mi),
                                int(se or 0), 0, 0, -1))
        except ValueError:
            pass
    m = LOG_TIMESTAMP_PATTERNS[1].search(raw)
    if m:
        mon, d, h, mi, se, y = m.groups()
        mo = MONTHS_EN.get(mon)
        if mo:
            try:
                return time.mktime((int(y), mo, int(d), int(h), int(mi),
                                    int(se), 0, 0, -1))
            except ValueError:
                pass
    return None


# ── сравнение чисел с допуском на округление (7,56 ГБ в логе -> "7,6 ГБ" в
#    прозе - легитимное округление; версии с 2+ точками допуска не имеют) ────

def _to_float(tok):
    try:
        return float(tok)
    except ValueError:
        return None


def _log_number_floats(norm_text):
    out = []
    for tok in NUMBER_RE.findall(norm_text):
        if tok.count(".") <= 1:
            v = _to_float(tok)
            if v is not None:
                out.append(v)
    return out


def _number_ok(draft_num, space_norm, space_floats, tol_rel):
    if draft_num in space_norm:
        return True
    if draft_num.count(".") > 1:
        return False  # версия/составной токен ("0.32.6") - только побайтово
    dv = _to_float(draft_num)
    if dv is None:
        return False
    for lv in space_floats:
        denom = max(abs(dv), abs(lv), 1e-9)
        if abs(dv - lv) / denom <= tol_rel:
            return True
    return False


def _set_ok(toks, space_norm):
    return all(t in space_norm for t in toks) if toks else True


def _nums_ok(nums, space_norm, space_floats, tol_rel):
    return all(_number_ok(n, space_norm, space_floats, tol_rel) for n in nums) \
        if nums else True


def _split_cmd_output(lines):
    """Строка команды ("$ ...") против строк вывода под ней."""
    cmd = [ln for ln in lines if CMD_LINE_RE.match(ln.strip())]
    out = [ln for ln in lines if not CMD_LINE_RE.match(ln.strip())]
    return "\n".join(cmd), "\n".join(out)


# ── деление :::pre на «команда + её вывод» - несколько команд в ОДНОМ блоке
#    бывают сняты в РАЗНЫХ логах (живой случай - guide-kak-skachat-s-github,
#    "$ git --version" в файле 01, "$ command -v git" в файле 06, один
#    :::pre блок держит обе для читателя) ─────────────────────────────────────

def split_segments(body_lines):
    segments, cur = [], []
    for ln in body_lines:
        if CMD_LINE_RE.match(ln.strip()):
            if cur:
                segments.append(cur)
            cur = [ln]
        else:
            cur.append(ln)
    if cur:
        segments.append(cur)
    return segments or [body_lines]


# ── вердикт по одной единице проверки (весь :::figure либо один сегмент
#    :::pre) ────────────────────────────────────────────────────────────────

def check_unit(lines, scope, logs, min_anchor, min_digits, tol_rel, peer_logs=None):
    """Факты делятся на СИЛЬНЫЕ (домены+числа из строк ВЫВОДА - обязаны
    сойтись ВСЕГДА) и СЛАБЫЕ (домены+числа, которые встретились ТОЛЬКО в
    самой строке "$ команда", плюс ЛЮБЫЕ локальные пути) - слабые обязаны
    сойтись, только если анчор-строка в этом пространстве не нашлась.

    Почему так. Строка "$ ..." часто РЕКОНСТРУИРОВАНА для читателя (реальный
    вызов в логе синтезирован в иллюстративную команду, живые случаи -
    guide-lovable: команда несёт стандартный UA "Mozilla/5.0", которого в
    логе нет, хотя ВСЕ строки вывода под ней - HTTP/2 403, cf-mitigated,
    cf-ray - совпадают дословно; guide-claude-mcp: команда+URL совпадают, а
    локальный путь "File modified: .../mcp-demo" отличается только из-за
    scratch-каталога сессии). Строка ВЫВОДА - это то, что реально пришло от
    системы, ей поблажек нет: расхождение там - и есть дефект r8 (test 3,
    «real 0m18.121s» вместо «real 0m1.268s» стоит в СТРОКЕ ВЫВОДА, не команды)."""
    text = "\n".join(lines)
    anchors = anchor_lines(lines, min_anchor)
    cmd_text, out_text = _split_cmd_output(lines)
    strong_nums = qualifying_numbers(out_text, min_digits)
    strong_doms = domain_tokens(out_text)
    weak_nums = qualifying_numbers(cmd_text, min_digits) - strong_nums
    weak_doms = domain_tokens(cmd_text) - strong_doms
    paths = path_tokens(text)
    tried = {"anchors": anchors,
             "numbers": sorted(strong_nums | weak_nums),
             "tokens": sorted(strong_doms | weak_doms | paths), "scope": scope}
    any_facts = bool(strong_nums or strong_doms or weak_nums or weak_doms or paths)

    # ── названные точки замера: сильный факт, анчор их не отменяет ────────────
    # Ищем по СТРУКТУРНЫМ строкам ВСЕХ логов сразу (точка могла быть записана
    # в соседний файл того же прогона), но только по ним - см. блок про дыру
    # у определения VANTAGE_RE.
    vpoints = vantage_points(text)
    if vpoints:
        mark_space = " ".join(rec.get("markers", "") for rec in logs.values())
        unbacked = sorted(name for name, st in vpoints.items() if st not in mark_space)
        tried["vantage"] = {"заявлено": sorted(vpoints), "без опоры в логе": unbacked}
        if unbacked:
            # Факт был назван и не подтвердился - это UNCONFIRMED, роняет гейт.
            return {"ok": False, "verifiable": True, "how": None, "file": None,
                    "evidence": None, "tried": tried}

    # ── счёт собственных замеров: сильный факт, анчор его не отменяет ─────────
    # Сводка «двенадцать замеров, от 13,2 до 15,1» обязана стоять на МАШИННОМ
    # перечне в логах, а не на памяти автора: границы диапазона гейт находит в
    # логах и успокаивается, а сам счёт и то, что это именно границы, до этой
    # оси не проверял никто - см. блок про дыру у TALLY_CNT_RE.
    tbad, tclaims, tfound = tally_mismatches(text, logs, tol_rel, min_digits)
    if tclaims:
        tried["tally"] = {"заявлено": tclaims,
                          "перечень в логах": [f["строка"] for f in tfound],
                          "без опоры": tbad}
    if tbad:
        return {"ok": False, "verifiable": True, "how": None, "file": None,
                "evidence": None, "tried": tried}

    # ── состояние чужого сервиса против парной страницы волны ─────────────────
    # Сильный факт: у соседа по волне лежит более свежая улика по тому же
    # экрану, и она опровергает нашу. Анчор такое не отменяет - наш лог тут
    # совпадает с текстом идеально, в этом и дыра.
    conflicts = cross_wave_conflicts(text, logs, peer_logs or {})
    if conflicts:
        tried["cross_wave"] = [{"цитата": q, "лог соседа": f, "строка": s}
                               for q, f, s in conflicts]
        return {"ok": False, "verifiable": True, "how": None, "file": None,
                "evidence": None, "tried": tried}

    def verdict(name, space_norm, anchor_hit):
        floats = _log_number_floats(space_norm)
        if not (_set_ok(strong_doms, space_norm)
                and _nums_ok(strong_nums, space_norm, floats, tol_rel)):
            return None
        if not anchor_hit and not (
                _set_ok(weak_doms, space_norm)
                and _nums_ok(weak_nums, space_norm, floats, tol_rel)
                and _set_ok(paths, space_norm)):
            return None
        if not (any_facts or anchor_hit):
            return None
        how = ("анчор+факты" if anchor_hit else "факты") if any_facts else "анчор"
        matched_anchor = next((a for a in anchors if a in space_norm), None)
        ev = (f"числа {sorted(strong_nums | weak_nums)} "
              f"домены {sorted(strong_doms | weak_doms)} пути {sorted(paths)}")
        if matched_anchor:
            ev += f" · анчор «{matched_anchor[:60]}»"
        return {"ok": True, "verifiable": True, "how": how, "file": name,
                "evidence": ev, "tried": tried}

    if scope == "file":
        for name, rec in logs.items():
            anchor_hit = any(a and a in rec["norm"] for a in anchors)
            r = verdict(name, rec["norm"], anchor_hit)
            if r:
                return r
    else:
        combined = " ".join(rec["norm"] for rec in logs.values())
        anchor_hit = any(a and a in combined for a in anchors)
        r = verdict("(весь terminal-outputs/)", combined, anchor_hit)
        if r:
            return r

    # 🔴 калибровка по живому корпусу (по решению автора): из 29 неподтверждённых
    # блоков на всём корпусе 14 - фигуры с ПОДПИСЬЮ БЕЗ единой цифры/домена/
    # пути ("Карточка замера: какие сервисы ответили, а какие дали ошибку") -
    # для них у гейта физически НЕТ факта для сверки (сама картинка машине не
    # видна). Красить их наравне с блоком, где число РАСХОДИТСЯ с логом -
    # смешивать «нечем проверить» с «проверили и не сошлось», две разные вещи
    # и разные действия для автора. UNVERIFIABLE - не роняет вердикт (мягкий
    # флаг «добавь цифру в подпись или проверь глазами»), UNCONFIRMED - роняет
    # (факт был, и он не подтвердился - это и есть дефект r8).
    return {"ok": False, "verifiable": any_facts, "how": None, "file": None,
            "evidence": None, "tried": tried}


# ── вердикт по одному блоку (:::figure - одна единица, :::pre - по сегментам) ─

def check_block(block, logs, min_anchor, min_digits, tol_rel, peer_logs=None):
    """Блок подтверждён, если подтверждена КАЖДАЯ его единица проверки.
    :::figure - подпись целиком, ищется по ВСЕМУ terminal-outputs/ разом
    (подпись часто сводит числа нескольких прогонов). :::pre - по СЕГМЕНТАМ
    ("$ команда" + её вывод, до следующей "$"): каждый сегмент обязан сойтись
    В ОДНОМ файле (буквальный прогон), но РАЗНЫЕ сегменты ОДНОГО блока могут
    сойтись в РАЗНЫХ файлах - несколько команд в одном :::pre снимаются не
    всегда одним прогоном (живой случай guide-kak-skachat-s-github)."""
    if block["kind"] == "figure":
        text = figure_text(block["body"])
        units = [([ln for ln in text.splitlines() if ln.strip()], "corpus")]
    elif block["kind"] == "html":
        # сырой HTML-блок (r15): карточка замера в разметке. Внутри бывает и
        # терминальный вывод (<pre> с «$ команда»), и сводная проза с числами
        # из НЕСКОЛЬКИХ прогонов ("проверено · версия 2.1.186 ·
        # четыре прогона"). Первый случай судим как :::pre - посегментно и
        # файл-в-файл (буквальный прогон), второй как :::figure - целиком по
        # всему каталогу логов (карточка сводит числа разных прогонов, требовать
        # их в ОДНОМ файле - гарантированный ложный дефект).
        lines = [ln for ln in block["body"] if ln.strip()]
        if any(CMD_LINE_RE.match(ln.strip()) for ln in lines):
            units = [(seg, "file") for seg in split_segments(lines)]
        else:
            units = [(lines, "corpus")]
    else:
        units = [(seg, "file") for seg in split_segments(block["body"])]

    results = [check_unit(lines, scope, logs, min_anchor, min_digits, tol_rel, peer_logs)
              for lines, scope in units]

    if all(r["ok"] for r in results):
        files = sorted({r["file"] for r in results})
        return {"ok": True, "verifiable": True, "how": "+".join(sorted({r["how"] for r in results})),
                "file": "; ".join(files), "evidence": " || ".join(r["evidence"] for r in results),
                "tried": {"units": [r["tried"] for r in results]}}

    bad = [r for r in results if not r["ok"]]
    verifiable = any(r["verifiable"] for r in bad)
    return {"ok": False, "verifiable": verifiable, "how": None, "file": None,
            "evidence": None, "tried": {"units": [r["tried"] for r in results]},
            "unit_results": results}


def mtime_diagnostics(logs, drift_minutes):
    """Справочная ось: расхождение mtime файла и самоописанной метки внутри
    него. НИКОГДА не входит в вердикт - см. докстринг "чего не ловит"."""
    out = []
    for name, rec in sorted(logs.items()):
        ts = rec["embedded_ts"]
        if ts is None:
            continue
        drift = abs(rec["mtime"] - ts) / 60.0
        if drift > drift_minutes:
            out.append((name, drift))
    return out


# ── прогон по файлу ───────────────────────────────────────────────────────────

def collect_blocks(text):
    """own=measure блоки ОБЕИХ форм в порядке появления в файле (r15):
    директивная (:::pre / :::figure own=measure) + сырая HTML (любой элемент
    с data-own="measure")."""
    directive = [b for b in parse_blocks(text) if b["kind"] in ("pre", "figure")
                 and own_kind(b["attrs"]) == OWN_KIND_TARGET]
    raw = parse_html_own_blocks(text)
    return sorted(directive + raw, key=lambda b: b["line"])


def _block_form(b):
    if b["kind"] == "html":
        cls = re.search(r'class\s*=\s*"([^"]*)"', b.get("attrs") or "")
        tag = f'<{b["tag"]}' + (f' class="{cls.group(1)}"' if cls else "") + ">"
        return f'сырая HTML {tag} data-own="measure"'
    return f':::{b["kind"]} own=measure'


def run(draft_path, to_dir, min_anchor, min_digits, drift_minutes, tol_pct):
    text = read(draft_path)
    blocks = collect_blocks(text)
    logs = load_logs(to_dir)
    source = draft_path
    fallback = None
    # 🔴 второй проход (r15): если в ЧЕРНОВИКЕ нет ни одной формы own=measure,
    # а рядом лежит собранная index.html и в ней блоки ЕСТЬ - разметка живёт
    # только в странице (черновик мигрировал/собран из секций). Молча пройти
    # мимо тут - тот же ложный зелёный, ради которого правка и делалась.
    if not blocks:
        page = os.path.join(os.path.dirname(os.path.abspath(draft_path)), "index.html")
        if os.path.isfile(page):
            try:
                page_text = read(page)
            except OSError:
                page_text = ""
            page_blocks = collect_blocks(page_text)
            if page_blocks:
                blocks, source, fallback = page_blocks, page, page
    peer_logs = load_peer_logs(os.path.dirname(os.path.abspath(draft_path)))
    results = []
    for b in blocks:
        r = check_block(b, logs, min_anchor, min_digits, tol_pct / 100.0, peer_logs)
        r["line"] = b["line"]
        r["kind"] = b["kind"]
        r["form"] = _block_form(b)
        r["snippet"] = (b["body"][0].strip() if b["body"] else "")[:90]
        results.append(r)
    drift = mtime_diagnostics(logs, drift_minutes)
    markers = detect_own_markers(text, logs) if not blocks else []
    return {"blocks": results, "logs": sorted(logs), "log_dir": to_dir,
            "peer_logs": len(peer_logs),
            "mtime_drift": drift, "source": source, "fallback_page": fallback,
            "negations": [{"line": n, "phrase": p, "snippet": s}
                          for n, p, s in unprovable_negations(text)],
            "pics": dict(zip(("без опоры", "заявлено", "перечень в логах"),
                             pic_count_mismatches(text, logs))),
            "markers": [{"label": l, "line": n, "snippet": s} for l, n, s in markers],
            "forms": {"директива :::": sum(1 for b in blocks if b["kind"] != "html"),
                      "сырая HTML data-own": sum(1 for b in blocks if b["kind"] == "html")}}


