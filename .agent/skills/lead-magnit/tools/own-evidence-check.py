def detect_own_markers(text, logs):
    """[(метка, строка|None, фрагмент)] - следы собственного замера в статье."""
    found = []
    if logs:
        names = ", ".join(sorted(logs)[:4]) + ("…" if len(logs) > 4 else "")
        found.append((f"непустой terminal-outputs/ ({len(logs)} файлов логов)",
                      None, names))
    lines = text.splitlines()
    for pat, label in OWN_MARKER_PATTERNS:
        for i, ln in enumerate(lines, 1):
            m = pat.search(ln)
            if m:
                s = re.sub(r"\s+", " ", ln.strip())
                start = max(0, m.start() - 30)
                found.append((label, i, s[start:start + 110].strip()))
                break
    return found


def figure_text(body):
    """alt+caption текст фигуры - то немногое, что можно машинно сверить с логом.

    Продолжение без нового ключа "поле:" в начале строки уезжает в текущее
    поле (перенос длинной подписи на вторую строку в редких случаях).
    """
    fields = {}
    cur = None
    for ln in body:
        s = ln.strip()
        m = re.match(r"^(alt|caption)\s*:\s*(.*)$", s, re.I)
        if m:
            cur = m.group(1).lower()
            fields[cur] = m.group(2)
        elif cur and s:
            fields[cur] = (fields[cur] + " " + s).strip()
    return "\n".join(v for v in fields.values() if v)


# ── нормализация и извлечение улик ────────────────────────────────────────────

def strip_placeholders(text):
    return PLACEHOLDER_RE.sub(" ", text)


def _merge_thousands(text):
    """"11 756 500" -> "11756500": группировка тысяч пробелом/nbsp - ОДНО
    число, не три (см. THOUSANDS_RE)."""
    return THOUSANDS_RE.sub(lambda m: re.sub(r"[ \xa0]", "", m.group(0)), text)


def normalize(text):
    """Единая форма для сравнения черновика с логом.

    Порядок важен: группировка тысяч схлопывается ДО того, как пробелы
    станут незначимыми (иначе нечего схлопывать), плейсхолдеры вырезаются
    раньше домашнего каталога (иначе "<ссылка на дистрибутив>" мог бы
    зацепиться /-путём), дробная запятая правится раньше сравнения по
    подстроке, регистр и пробелы - в конце.
    """
    t = _merge_thousands(text)
    t = strip_placeholders(t)
    t = HOME_RE.sub("/users/~", t)
    t = re.sub(r"(?<=\d),(?=\d)", ".", t)
    t = t.lower()
    t = re.sub(r"\s+", " ", t).strip()
    return t


def _strip_dates(text):
    t = DATE_PHRASE_RE.sub(" ", text)
    t = DATE_NUMERIC_RE.sub(" ", t)
    t = ISO_DATE_RE.sub(" ", t)
    t = TIME_RE.sub(" ", t)
    return t


def _scale_word_units(text):
    """"7,6 млн" -> "7600000", "300 тыс" -> "300000" - масштаб словом, число
    после точки/запятой раскрывается в абсолютное (см. MILLION_RE)."""
    def scale(m, mult):
        v = _to_float(m.group(1).replace(",", "."))
        return str(int(round(v * mult))) if v is not None else m.group(0)
    text = MILLION_RE.sub(lambda m: scale(m, 1_000_000), text)
    text = THOUSAND_WORD_RE.sub(lambda m: scale(m, 1_000), text)
    return text


def qualifying_numbers(text, min_digits):
    """Значимые числа блока: даты/время вычищены заранее (иначе формат дат в
    прозе и в логе почти никогда не совпадёт побайтово - это не про факты),
    квантификаторы regex ("{1,3}") тоже вычищены (это синтаксис показанной
    команды, а не измеренное число - см. REGEX_QUANTIFIER_RE), «X млн/тыс»
    раскрывается в абсолютное число ДО сравнения (см. MILLION_RE)."""
    t = _merge_thousands(text)
    t = strip_placeholders(t)
    t = _strip_dates(t)
    t = REGEX_QUANTIFIER_RE.sub(" ", t)
    t = re.sub(r"(?<=\d),(?=\d)", ".", t)
    t = _scale_word_units(t)
    nums = set()
    for m in NUMBER_RE.finditer(t):
        tok = m.group(0)
        if BARE_YEAR_RE.match(tok):
            continue
        digits = re.sub(r"\D", "", tok)
        if "." in tok or len(digits) >= min_digits:
            nums.add(tok)
    return nums


def domain_tokens(text):
    """Домены из НАСТОЯЩИХ URL (после http(s):// или www.) - сильный факт:
    подменённый в примере домен, которого не было в прогоне, обязан красить
    блок ВСЕГДА (живой дефект - intora-design.ru, см. докстринг «что ловит»)."""
    t = strip_placeholders(text)
    return {m.group(1).lower() for m in DOMAIN_RE.finditer(t)}


def path_tokens(text):
    """Локальные пути блока - СЛАБЫЙ факт: домашний каталог рабочей машины
    (scratchpad/временные каталоги сессии, имя проекта) легитимно отличается
    от иллюстративного пути в прозе (живой калибровочный случай -
    guide-claude-mcp: реальный прогон писал в /private/tmp/.../mcp-demo,
    черновик для читателя показывает ~/mcp-demo - тот же факт, другая
    оболочка). Обязателен, только когда анчор-строка НЕ нашлась вовсе
    (см. check_block) - иначе локальный путь один топит блок с совпавшей
    командой, доменом и текстом подтверждения."""
    t = strip_placeholders(text)
    toks = set()
    for m in PATH_RE.finditer(t):
        p = m.group(0)
        if len(re.sub(r"\W", "", p)) >= 4:
            toks.add(normalize(p))
    return toks


# ── ось «названа точка замера» (правка r14, по решению автора) ───────────────────────
#
# 🔴 ДЫРА, которую закрывает эта ось. Гейт строил анчоры из доменов настоящих
# URL и значимых чисел, поэтому КАЧЕСТВЕННОЕ утверждение без числа и без домена
# проходило бесплатно. Живой случай guide-neyroset-kandinskiy (круг 7): блок
# data-own="measure" писал «Я проверил его с трёх независимых точек… Из сети
# США браузер получает прямой отказ соединения», а лог называл свои три точки
# иначе («мак автора», «сервер в Москве», «архив интернета») и слова «США» не
# содержал вовсе. Ни домена, ни числа во фразе про США нет - проверять машине
# было нечего, и придуманной оказалась не только точка, но и характер ответа
# (таймаут против «прямого отказа»).
#
# ЧТО ПРОВЕРЯЕМ. Если own-блок НАЗЫВАЕТ место, откуда шёл замер («из сети X»,
# «через сеть X», «с сервера в X», «на сервере в X», «из дата-центра в X»),
# это имя обязано стоять в СТРУКТУРНОЙ строке лога - в шапке (`#`), в разделе
# (`--- точка 2: сервер в Москве ---`) или в строке команды (`$ ...`). Именно
# в структурной, а не где угодно в файле: иначе правило обходится одной
# оговоркой в прозе лога («точку X мы не мерили»), и зелёный снова ложный.
#
# КАЛИБРОВКА ПЕРЕД ЖЁСТКОСТЬЮ (по живому корпусу lead-magnit-work, по решению автора):
# на ВСЕХ черновиках с непустым terminal-outputs/ такая фраза нашлась ровно
# ОДНА - «с сервера в Москве» у guide-neyroset-kandinskiy, и она подтверждена
# строкой раздела лога. Новых красных по корпусу: 0. То есть ось узкая и
# корпус ею не топится, поэтому она СИЛЬНЫЙ факт (роняет блок), а не advisory.
VANTAGE_RE = re.compile(
    r"(?:из\s+сети|через\s+сеть|с\s+сервера\s+в|на\s+сервере\s+в|"
    r"из\s+дата-?центра\s+в|с\s+адреса\s+в|с\s+точки\s+в)\s+"
    r"([А-ЯЁ][А-Яа-яЁё\-]{2,}|[A-Z][A-Za-z\-]{2,}|США|ЕС|СНГ|ОАЭ)", re.I)

LOG_MARKER_RE = re.compile(r"^\s*(?:-{2,}|#|\$|точка\s*\d)", re.I)


def vantage_points(text):
    """Названия точек замера, заявленные в own-блоке: {как в тексте: стем}.

    Стем - слово без последней буквы (падежное окончание): «Москве» -> «москв»,
    и та же основа найдётся в логе, как бы он ни склонял («Москва», «Москве»).
    Короткие аббревиатуры (США, ЕС) не режем - у них окончаний нет."""
    out = {}
    for m in VANTAGE_RE.finditer(strip_placeholders(text or "")):
        tok = m.group(1)
        out[tok] = tok.lower()[:-1] if len(tok) > 4 else tok.lower()
    return out


def marker_text(raw):
    """Структурные строки лога: шапка, разделы, строки команд. Только они
    считаются заявкой «такая точка в прогоне была»."""
    return normalize(" ".join(ln for ln in (raw or "").splitlines()
                              if LOG_MARKER_RE.match(ln)))


# ── ось «СЧЁТ собственных замеров» (правка r14, по решению автора) ───────────────────
#
# 🔴 ДЫРА, которую закрывает эта ось. Ось VANTAGE выше отвечает на вопрос
# «ОТКУДА мерили», а «СКОЛЬКО РАЗ мерили» проезжало бесплатно: гейт сверяет
# значимые числа блока с логами, и сводная фраза «десять замеренных генераций
# того дня уложились в разброс от 13,9 до 15,1 секунды» проходила зелёной,
# потому что 13,9 и 15,1 в логах ЛЕЖАТ. Не лежало в логах другое - сам счёт
# «десять» и то, что 13,9 это нижняя граница.
#
# ЖИВОЙ СЛУЧАЙ guide-neyroset-kandinskiy (круг 14, по решению автора). Сводку написали
# руками в круге 9, когда замеров было десять. Дальше круг 7 добрал замер 15,1
# кросс-прогоном, круг 10 добрал 13,2 - и ни разу не пересчитал сводку. В итоге
# фраза опровергалась соседним предложением В ТОМ ЖЕ АБЗАЦЕ («на 13,2 во
# втором»), стояла на странице в двух местах, и три числа уехали читателю.
# Класс дефекта тот же, что у VANTAGE: текст обещает то, чего не было.
#
# ПОЧЕМУ РУЧНОЙ СЧЁТ ЗДЕСЬ НЕ РАБОТАЕТ В ПРИНЦИПЕ. Сводка стареет молча.
# Замеры дописываются доборами в РАЗНЫЕ файлы и в разных формах записи (строка
# «секунд до картинки: 15.1», строка таблицы хвостов стиля), и человек, который
# добрал один замер, не перечитывает всю папку логов. Поэтому ось требует не
# «правильного числа», а МАШИННОГО ПЕРЕЧНЯ: назвал счёт - положи рядом с логами
# вывод скрипта, который этот счёт СЧИТАЕТ. Строка перечня узнаётся по форме
# «ИТОГО замеров: 12 · минимум 13.2 · максимум 15.1».
#
# ЧТО ИМЕННО ПРОВЕРЯЕТСЯ, когда ось сработала:
#   1. счёт из текста == счёт из строки перечня в логах;
#   2. если текст называет диапазон («от 13,2 до 15,1»), а перечень несёт
#      минимум/максимум - границы обязаны совпасть с допуском на округление;
#   3. перечня в логах нет вовсе -> блок красный: пересчитать нечем.
#
# ЭКСЕМПЦИЯ САМОПЕРЕЧИСЛЕНИЯ (без неё ось топит честный корпус). Если фраза
# сама перечисляет столько же измеренных значений, сколько заявила («Три
# прогона подряд заняли 36.760, 27.060 и 17.268 секунды» - guide-ii-dlya-
# psihologa), счёт проверять нечего: каждое значение и так сверяется с логом
# сильными фактами, а счёт виден глазами. Такие фразы ось пропускает.
#
# КАЛИБРОВКА ПЕРЕД ЖЁСТКОСТЬЮ (живой корпус lead-magnit-work, по решению автора,
