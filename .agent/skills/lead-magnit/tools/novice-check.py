def _selftest_fixtures():
    """Прогон фикстурных файлов оси 4, если каталог рядом. (ok, fail, всего)."""
    here = os.path.dirname(os.path.abspath(__file__))
    fixdir = os.path.join(here, "tests", "tech-detail")
    if not os.path.isdir(fixdir):
        print("  фикстур рядом нет (tests/tech-detail), ветки словаря проверены выше")
        return 0, 0, 0
    ok = bad = 0
    for name in sorted(os.listdir(fixdir)):
        if not name.endswith(".md"):
            continue
        want_fail = name.startswith("pos-")
        raw = read(os.path.join(fixdir, name))
        res = analyse(raw, False, set(), dict(THRESHOLDS), hard=True)
        got = res["tech_detail_hits"] > 0
        good = got == want_fail
        ok += 1 if good else 0
        bad += 0 if good else 1
        print("  %s фикстура %-26s вхождений оси 4: %d (ждали %s)"
              % ("ok  " if good else "FAIL", name, res["tech_detail_hits"],
                 ">0" if want_fail else "0"))
    return ok, bad, ok + bad


def selftest():
    print("novice-check --selftest: ветки словаря оси 4")
    ok = bad = 0
    for what, text, want_n, want_term in SELFTEST_CASES:
        n, by_term = scan_tech_detail(text, set())
        good = (n == want_n) and (want_term is None or want_term in by_term)
        ok += 1 if good else 0
        bad += 0 if good else 1
        print("  %s %-46s вхождений %d (ждали %d)%s"
              % ("ok  " if good else "FAIL", what, n, want_n,
                 "" if want_term is None else " ярлык «%s»" % want_term))
        if not good and by_term:
            print("         поймано: %s" % ", ".join(sorted(by_term)))
    print("novice-check --selftest: ветки склейки ячеек (R-46), вход - разметка")
    for what, raw_html, want_n, want_term in SELFTEST_HTML_CASES:
        n, by_term = scan_tech_detail(html_visible_text(raw_html), set())
        good = (n == want_n) and (want_term is None or want_term in by_term)
        ok += 1 if good else 0
        bad += 0 if good else 1
        print("  %s %-46s вхождений %d (ждали %d)%s"
              % ("ok  " if good else "FAIL", what, n, want_n,
                 "" if want_term is None else " ярлык «%s»" % want_term))
        if not good and by_term:
            print("         поймано: %s" % ", ".join(sorted(by_term)))
    fok, fbad, _ = _selftest_fixtures()
    ok += fok
    bad += fbad
    print("novice-check --selftest: веток ok %d, FAIL %d" % (ok, bad))
    return 1 if bad else 0


def parse_args(argv=None):
    p = argparse.ArgumentParser(
        description="Гейт «понятно новичку»: жаргон/1k, код-блоки, терминальные скрины")
    p.add_argument("target", nargs="?", help="draft.md или index.html")
    p.add_argument("--stage", choices=("auto", "draft", "page"), default="auto",
                   help="какой вход читать (по умолчанию - по расширению/содержимому)")
    p.add_argument("--revision", action="store_true",
                   help="ревизия легаси: терминальные скрины - замечание, не брак")
    p.add_argument("--doors", default=os.environ.get("NOVICE_DOORS") or None,
                   help="канон дверей (door-titles-canon.json) для белого списка "
                        "названий продуктов; файла нет - гейт работает без него")
    p.add_argument("--max-jargon-per-1k", type=float, default=None)
    p.add_argument("--warn-jargon-per-1k", type=float, default=None)
    p.add_argument("--max-raw-code", type=int, default=None)
    p.add_argument("--max-code-per-1k", type=float, default=None)
    p.add_argument("--json", action="store_true", help="машинно-читаемый вывод")
    p.add_argument("--selftest", action="store_true",
                   help="офлайн-прогон веток словаря оси 4 и фикстур рядом")
    return p.parse_args(argv)


def main(argv=None):
    a = parse_args(argv)
    if a.selftest:
        return selftest()
    if not a.target:
        print("novice-check: не указан файл (draft.md или index.html)", file=sys.stderr)
        return 3
    path = os.path.expanduser(a.target)
    if os.path.isdir(path):
        for cand in ("index.html", "draft.md"):
            if os.path.isfile(os.path.join(path, cand)):
                path = os.path.join(path, cand)
                break
    if not os.path.isfile(path):
        print(f"novice-check: нет файла {path} - проверять нечего", file=sys.stderr)
        return 3
    raw = read(path)
    if not raw.strip():
        print(f"novice-check: файл пуст {path}", file=sys.stderr)
        return 3

    if a.stage == "draft":
        is_html = False
    elif a.stage == "page":
        is_html = True
    else:
        is_html = looks_like_html(raw, path)

    th = dict(THRESHOLDS)
    if a.max_jargon_per_1k is not None:
        th["jargon_fail"] = a.max_jargon_per_1k
    if a.warn_jargon_per_1k is not None:
        th["jargon_warn"] = a.warn_jargon_per_1k
    if a.max_raw_code is not None:
        th["raw_code_fail"] = a.max_raw_code
    if a.max_code_per_1k is not None:
        th["code_per_1k_fail"] = a.max_code_per_1k

    whitelist = load_product_whitelist(a.doors)
    res = analyse(raw, is_html, whitelist, th, hard=not a.revision)
    res["file"] = path
    res["doors_whitelist"] = len(whitelist)

    if a.json:
        print(json.dumps(res, ensure_ascii=False, indent=2))
    else:
        print("\n".join(render(res, path, th)))
    return RC[res["verdict"]]


if __name__ == "__main__":
    sys.exit(main())
