def scan_tech_detail(text, whitelist):
    """(hits, by_term) по классу нулевой терпимости.

    Отличие от scan_jargon: НЕТ послабления на объяснение в том же предложении.
    Объяснить новичку код 307 нельзя - его можно только не писать: любое
    вхождение остаётся вхождением. Послабления, которые остаются: маска
    названий продуктов и КОД-СЛОВО кириллицей капсом.
    """
    masked = mask_whitelist(text, whitelist)
    sents = sentences_with_spans(masked)
    by_term, total = {}, 0
    for name, rx, fix, guard in TECH_DETAIL_RX:
        for m in rx.finditer(masked):
            frag = m.group(0)
            if CAPS_CYR.match(frag):
                continue
            s_start, s_end, s_text = _sentence_of(sents, m.start())
            if guard:
                around = (s_text[:m.start() - s_start] + " "
                          + s_text[m.end() - s_start:]) if s_text else ""
                if not TECH_DETAIL_CONTEXT.search(around):
                    continue
            rec = by_term.setdefault(name, {"n": 0, "example": "", "fix": fix})
            rec["n"] += 1
            total += 1
            if not rec["example"] and s_text:
                rec["example"] = _short(s_text)
    return total, by_term


