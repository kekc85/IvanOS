# правил. Внутри одной ячейки правило работает как работало.
CELL_BREAK = "\x1f"
# зазор правила: те же «любые знаки», но конец предложения и граница ячейки в
# него не входят. Собирается кодом, чтобы у пяти правил не разъехались классы
_GAP = r"[^.!?" + CELL_BREAK + r"|]"

