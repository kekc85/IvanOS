# R-46: границы ячейки/строки таблицы и пункта списка. Ровно эти теги: у них
# рендер даёт читателю ОТДЕЛЬНУЮ единицу текста, а тег-в-пробел склеивал их в
# одну строку и правила с зазором начинали читать соседнюю ячейку как своё
# продолжение. Абзацы (<p>) сюда не берутся намеренно: у них и так стоит точка,
# лишний разделитель менял бы числа корпуса без своей причины
CELL_EDGE_RX = re.compile(r"</?(?:td|th|tr|li|dt|dd)\b[^>]*>", re.I)


def html_visible_text(raw):
    """Видимая проза собранной страницы: без шаблона, без кода, без атрибутов."""
    t = drop_ranges(raw, HTML_TEMPLATE_ZONES)
    t = drop_ranges(t, HTML_CODE_ZONES)
    t = CELL_EDGE_RX.sub(" " + CELL_BREAK + " ", t)   # R-46: граница ячейки
    t = re.sub(r"<[^>]+>", " ", t)          # атрибуты уходят вместе с тегом
    t = _html.unescape(t)
    return clean_common(t)


MD_FRONTMATTER = re.compile(r"\A---\r?\n.*?\r?\n---\r?\n", re.S)


def md_visible_text(raw):
    """Видимая проза черновика: без YAML-шапки, без фенсов, без служебных полей.

    Из блока :::figure остаётся только caption (его читатель видит под кадром),
    alt/slug/размеры уходят - это метаданные, а не текст статьи. Блоки :::cta,
    :::related целиком служебные и в прозу не идут.
    """
    t = MD_FRONTMATTER.sub(" ", raw)
    # черновик легально несёт куски HTML (blockquote с cite, picture, table):
    # без этой зачистки в «прозу» уезжали значения атрибутов - cite="…", класс,
    # href - и гейт считал бы жаргон по разметке (замер: guide-ii-dlya-
    # prodazh давал «конфиг» из cite-атрибута цитаты)
    t = drop_ranges(t, HTML_CODE_ZONES + [r"<!--.*?-->"])
    t = re.sub(r"```.*?```", " ", t, flags=re.S)
    t = re.sub(r"~~~.*?~~~", " ", t, flags=re.S)
    t = re.sub(r"`[^`\n]*`", " ", t)
    t = re.sub(r":::(?:cta|related)\b.*?\n:::", " ", t, flags=re.S | re.I)

    def keep_caption(m):
        body = m.group(0)
        caps = re.findall(r"^\s*caption:\s*(.+)$", body, flags=re.M)
        return " " + " ".join(caps) + " "

    t = re.sub(r":::(?:figure|pre)\b.*?\n:::", keep_caption, t, flags=re.S | re.I)
    t = re.sub(r"^:::.*$", " ", t, flags=re.M)          # рамки остальных блоков
    t = re.sub(r"^\s*(?:slug|alt|w|h|ext|own|src|title):\s.*$", " ", t, flags=re.M)
    t = re.sub(r"!\[[^\]]*\]\([^)]*\)", " ", t)
    t = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", t)      # от ссылки остаётся текст
    t = re.sub(r"^\s*#{1,6}\s*", " ", t, flags=re.M)
    t = re.sub(r"\{#[\w-]+\}", " ", t)
    t = re.sub(r"<[^>]+>", " ", t)
    t = _html.unescape(t)
    t = re.sub(r"[*_>|~]", " ", t)
    return clean_common(t)


URL_RX = re.compile(r"https?://\S+|\bwww\.\S+", re.I)
DOMAIN_RX = re.compile(
    r"\b[\w-]+(?:\.[\w-]+)*\.(?:ru|com|org|net|io|dev|ai|me|app|co|sh|tech|pro|xyz)"
    r"(?:/\S*)?", re.I)


def clean_common(t):
    """Общий хвост очистки: видимые ссылки и домены не слова статьи."""
    t = URL_RX.sub(" ", t)
    t = DOMAIN_RX.sub(" ", t)
    t = t.replace(" ", " ")
    t = re.sub(r"[ \t  ]+", " ", t)
    t = re.sub(r"\n{3,}", "\n\n", t)
    return t


WORD_RX = re.compile(r"[A-Za-zА-Яа-яЁё0-9][A-Za-zА-Яа-яЁё0-9_+-]*", re.U)


def word_count(t):
    return len(WORD_RX.findall(t))


SENT_SPLIT = re.compile(r"(?<=[.!?…])\s+|\n+")


def sentences_with_spans(t):
    """[(начало, конец, текст)] - предложения с позициями в исходной строке."""
    out, pos = [], 0
    for part in SENT_SPLIT.split(t):
        idx = t.find(part, pos)
        if idx < 0:
            idx = pos
        out.append((idx, idx + len(part), part))
        pos = idx + len(part)
    return [(a, b, s) for a, b, s in out if s.strip()]


# ── белый список названий продуктов (необязательный канон дверей) ────────────

def load_product_whitelist(path):
    """Латинские имена продуктов из канона дверей. Файла нет - список пуст.

    🔒 Пути в скрипте не зашиты: канон приходит флагом --doors (или NOVICE_DOORS).
    На машине без него гейт работает ровно так же, просто без белого списка -
    это осознанное поведение, а не деградация: словарь и так не содержит имён
    продуктов, белый список лишь страхует от будущих совпадений.

    Слово, которое УЖЕ есть в словаре жаргона, в белый список не попадает
    никогда: иначе один чужой заголовок молча выключал бы ось.
    """
    if not path:
        return []
    path = os.path.expanduser(path)
    if not os.path.isfile(path):
        return []
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            data = json.load(f)
    except Exception:
        return []
    titles = []
    doors = data.get("doors") if isinstance(data, dict) else None
    if isinstance(doors, dict):
        for rec in doors.values():
            if isinstance(rec, dict) and isinstance(rec.get("title"), str):
                titles.append(rec["title"])
    phrases = set()
    for t in titles:
        # латинские токены и их пары: «Claude Code», «NVIDIA NIM», «n8n»
        toks = re.findall(r"\b[A-Za-z][A-Za-z0-9.+-]{1,}\b", t)
        for i, tok in enumerate(toks):
            phrases.add(tok.lower())
            if i + 1 < len(toks):
                phrases.add(f"{tok} {toks[i + 1]}".lower())
    out = []
    for p in sorted(phrases, key=len, reverse=True):
        if any(rx.fullmatch(p) for _, rx in JARGON_RX):
            continue                                    # словарь сильнее канона
        out.append(p)
    return out


def mask_whitelist(t, phrases):
    if not phrases:
        return t
    for p in phrases:
        t = re.sub(r"\b" + re.escape(p) + r"\b", lambda m: "·" * len(m.group(0)), t,
                   flags=re.I)
    return t


# ── ось 1: жаргон ────────────────────────────────────────────────────────────

CAPS_CYR = re.compile(r"^[А-ЯЁ][А-ЯЁ\d-]{2,}$")


def scan_jargon(text, whitelist):
    """(hits, per_1k, words, by_term) по видимой прозе.

    by_term: {ярлык: {"n": N, "example": "…предложение…"}} - в отчёт уходит
    топ-10 с числом и живым примером, иначе исправлять нечего: «жаргон 14/1k»
    без слов - непроверяемая надпись.
    """
    masked = mask_whitelist(text, whitelist)
    words = word_count(masked)
    sents = sentences_with_spans(masked)
    by_term, total = {}, 0
    for name, rx in JARGON_RX:
        for m in rx.finditer(masked):
            frag = m.group(0)
            if CAPS_CYR.match(frag):
                continue                                # КОД-СЛОВО двери
            s_start, s_end, s_text = _sentence_of(sents, m.start())
            if s_text and EXPLAIN_SENTENCE.search(s_text):
                continue
            if EXPLAIN_AFTER.match(masked[m.end():m.end() + 24]):
                continue
            if EXPLAIN_BEFORE.search(masked[max(0, m.start() - 40):m.start()]):
                continue
            if name in AMBIGUOUS:
                # сосед ищется в предложении БЕЗ самого совпадения, иначе
                # «репозиторий» подтверждал бы сам себя
                around = (s_text[:m.start() - s_start] + " "
                          + s_text[m.end() - s_start:]) if s_text else ""
                if not TECH_CONTEXT.search(around):
                    continue
            rec = by_term.setdefault(name, {"n": 0, "example": ""})
            rec["n"] += 1
            total += 1
            if not rec["example"] and s_text:
                rec["example"] = _short(s_text)
    per_1k = (total * 1000.0 / words) if words else 0.0
    return total, per_1k, words, by_term


def _sentence_of(sents, pos):
    for a, b, s in sents:
        if a <= pos < b:
            return a, b, s
    return 0, 0, ""


def _short(s, limit=150):
    # R-46: невидимый разделитель ячеек в отчёт не течёт - читателю он ничего не
    # говорит, а в цитате предложения выглядел бы мусорным байтом
    s = re.sub(r"\s+", " ", (s or "").replace(CELL_BREAK, " ")).strip()
    return s if len(s) <= limit else s[:limit - 1] + "…"


# ── ось 2: код-блоки ─────────────────────────────────────────────────────────

BLOCK_TAGS = (r"p|div|section|article|figure|figcaption|summary|details|li|ul|ol|"
              r"h[1-6]|tr|td|th|table|blockquote|br|hr|header|footer|aside|dl|dt|dd")
BLOCK_EDGE = re.compile(r"</?(?:" + BLOCK_TAGS + r")\b[^>]*>", re.I)


def _plain(fragment):
    return re.sub(r"\s+", " ", _html.unescape(re.sub(r"<[^>]+>", " ", fragment or ""))).strip()


def html_code_blocks(raw):
    """[(индекс, метка, содержимое, обвязан ли)] по блочным <pre> страницы.

    Обвязка ищется в 2 соседних абзацах с КАЖДОЙ стороны. «Абзац» берётся не по
    конкретному тегу, а по РЕНДЕРУ: страница разворачивается в поток строк
    (блочные теги дают перенос, инлайн - нет), и соседями блока становятся
    реальные видимые строки - подпись мокапа <span class="term-title">, ярлык
    <summary>Промпт - скопировать и вставить</summary>, обычный <p>. Разбор по
    списку тегов ловил только часть таких подписей и записывал в «сырые» 15 из
    16 промпт-блоков guide-ai-headshots, у которых обвязка есть (замер).

    Текст кнопок из окна выброшен заранее (HTML_TEMPLATE_ZONES): «Скопировать»
    на самой кнопке компонента - часть вёрстки, а не объяснение автора; иначе
    обвязанным оказывался бы любой блок подряд. Но САМ компонент копи-карточки
    (`.term-title` + `<button class="copybtn">`) - канонический визуал шаблона
    («формула 1» + кнопка «Скопировать» над блоком), не голый код: у подписи
    нет глагола («формула 1» - не «нажми»), поэтому обвязку по тексту она не
    даёт, а обвязку по КЛАССУ - должна (см. _has_card_wrapper ниже, тот же
    приём, что уже решённый кейс <summary>).
    """
    body = drop_ranges(raw, HTML_TEMPLATE_ZONES)
    codes = []

    def stash(m):
        codes.append(_html.unescape(re.sub(r"<[^>]+>", "", m.group(1))))
        return f"\n\x00{len(codes) - 1}\x00\n"

    stream = re.sub(r"<pre\b[^>]*>(.*?)</pre\s*>", stash, body, flags=re.S | re.I)
    stream = BLOCK_EDGE.sub("\n", stream)
    stream = _html.unescape(re.sub(r"<[^>]+>", " ", stream))
    lines = [l.strip() for l in stream.split("\n")]
    lines = [l for l in lines if l]

    idx = {}
    for i, l in enumerate(lines):
        m = re.fullmatch(r"\x00(\d+)\x00", l)
        if m:
            idx[int(m.group(1))] = i
    # позиции <pre> в ИСХОДНОМ raw (до drop_ranges) - card-обвязка ищется по
    # class="term-title"/class="copybtn", а они живут в button/span, часть из
    # которых HTML_TEMPLATE_ZONES уже вырезала из body. drop_ranges трогает
    # только head/script/style/комментарии/шапку/подвал/nav/related/button -
    # ни один из них не может содержать <pre>, поэтому счёт <pre> в raw и в
    # body совпадает один в один; если вдруг разъехался - card-проверку тихо
    # выключаем (safe fallback), чем гадать по неверному индексу.
    pre_spans = [m.span() for m in re.finditer(r"<pre\b[^>]*>.*?</pre\s*>", raw, re.S | re.I)]
    card_ok = len(pre_spans) == len(codes)

    def card_wrapped(n):
        if not card_ok:
            return False
        start = pre_spans[n][0]
        prev_end = pre_spans[n - 1][1] if n > 0 else 0
        window = raw[max(prev_end, start - 3000):start]
        return bool(CARD_WRAPPER.search(window))

    out = []
    for n, inner in enumerate(codes):
        i = idx.get(n)
        if i is None:                                   # <pre> внутри другого <pre>
            out.append((n, n, inner, True))
            continue
        # соседями считаются ДВЕ строки вплотную с каждой стороны, и соседний
        # <pre> - тоже сосед: он занимает слот и текста не даёт. Если бы блоки
        # кода пропускались, один абзац «нажми и увидишь» перед свалкой из
        # восьми блоков подряд легализовал бы всю свалку - ровно тот дефект,
        # ради которого ось и заведена
        near = lines[max(0, i - 2):i] + lines[i + 1:i + 3]
        near = [l for l in near if not l.startswith("\x00")]
        obvyazan = bool(COPY_MARKERS.search(" ".join(near))) or card_wrapped(n)
        out.append((n, n, inner, obvyazan))
    return out


def html_inline_code(raw):
    body = drop_ranges(raw, HTML_TEMPLATE_ZONES)
    body = re.sub(r"<pre\b[^>]*>.*?</pre\s*>", " ", body, flags=re.S | re.I)
    return len(re.findall(r"<code\b[^>]*>", body, re.I))


FENCE_RX = re.compile(r"^(?P<f>```|~~~)[^\n]*\n(?P<body>.*?)^(?P=f)\s*$", re.S | re.M)


def md_code_blocks(raw):
    """То же для черновика: фенсы ``` и блоки :::pre, обвязка - 2 абзаца рядом."""
    t = MD_FRONTMATTER.sub(lambda m: " " * len(m.group(0)), raw)
    paras = [(m.start(), _plain(m.group(0)))
             for m in re.finditer(r"(?:^|\n)(?!```|~~~|:::)([^\n]{3,})", t)]
    out = []
    spans = [(m.start(), m.end(), m.group("body")) for m in FENCE_RX.finditer(t)]
    for m in re.finditer(r":::pre\b.*?\n:::", t, re.S | re.I):
        spans.append((m.start(), m.end(), m.group(0)))
    for start, end, inner in sorted(spans):
        before = [x for p, x in paras if p < start][-2:]
        after = [x for p, x in paras if p > end][:2]
        ctx = " ".join(before + after)
        out.append((start, end, inner, bool(COPY_MARKERS.search(ctx))))
    return out


def md_inline_code(raw):
    t = MD_FRONTMATTER.sub(" ", raw)
    t = FENCE_RX.sub(" ", t)
    return len(re.findall(r"`[^`\n]+`", t))


# ── ось 3: терминальные скрины и мокапы окна терминала ───────────────────────

def html_terminal_shots(raw):
    """[(вид, улика)] - картинки-скрины терминала и мокапы с командами внутри.

    Мокап идёт ПЕРВЫМ циклом (не вторым, как раньше): контейнер с классом
    term/terminal/console/shell, внутри которого <pre> с командами оболочки.
    Мокап с текстом промпта внутри НЕ считается - это легальный копи-блок
    канона, а не чёрное окно. Span засчитанного мокапа запоминается, и <img>
    внутри него (иконка окна с src вида term-icon.svg) пропускается в цикле
    картинок ниже - иначе одна и та же карточка считалась бы ДВАЖДЫ: один раз
    как «мокап терминала», второй раз как «скрин» по её же иконке.
    """
    body = drop_ranges(raw, [r"<head\b[^>]*>.*?</head\s*>",
                             r"<script\b[^>]*>.*?</script\s*>",
                             r"<style\b[^>]*>.*?</style\s*>",
                             r"<!--.*?-->"])
    found = []
    mockup_spans = []
    for m in re.finditer(r"<(div|section|figure|aside)\b([^>]*)>", body, re.I):
        if not TERM_MOCKUP_CLASS.search("<x" + m.group(2) + ">"):
            continue
        chunk = body[m.end():m.end() + 4000]
        pre_m = re.search(r"<pre\b[^>]*>(.*?)</pre\s*>", chunk, re.S | re.I)
        if not pre_m:
            continue
        inner = _html.unescape(re.sub(r"<[^>]+>", "", pre_m.group(1)))
        if SHELL_CMD.search(inner) or SHELL_PROMPT.search(inner):
            found.append(("мокап терминала", _short(inner.strip(), 90)))
            mockup_spans.append((m.start(), m.end() + pre_m.end()))

    for m in re.finditer(r"<img\b[^>]*>", body, re.I):
        if any(a <= m.start() < b for a, b in mockup_spans):
            continue                                    # иконка уже засчитанного мокапа
        tag = m.group(0)
        alt = _attr(tag, "alt")
        src = _attr(tag, "src")
        cls = _attr(tag, "class")
        if SHOT_ALT_HINT.search(alt) or SHOT_ALT_HINT.search(cls):
            found.append(("скрин", f"<img alt=\"{_short(alt, 90)}\">"))
            continue
        toks = set(re.split(r"[^a-z0-9]+", (src or "").lower()))
        if toks & SHOT_SRC_TOKENS:
            found.append(("скрин", f"<img src=\"{_short(src, 90)}\">"))
    return found


def _attr(tag, name):
    m = re.search(name + r"\s*=\s*(?:\"([^\"]*)\"|'([^']*)')", tag, re.I)
    if not m:
        return ""
    return _html.unescape(m.group(1) if m.group(1) is not None else m.group(2))


def md_terminal_shots(raw):
    """Черновик: hero и :::figure с alt/caption про терминал + :::pre с командами."""
    found = []
    # hero живёт в YAML-шапке, а не в теле: главный кадр статьи с терминалом -
    # ровно тот сигнал «это не для меня», который стандарт и выносит
    fm = MD_FRONTMATTER.search(raw)
    if fm:
        for line in re.findall(r"^\s*(?:alt|og_image_alt|hero_alt):\s*(.+)$",
                               fm.group(0), re.M):
            if SHOT_ALT_HINT.search(line):
                found.append(("скрин (hero/og)", _short(line.strip("'\" "), 90)))
    for m in re.finditer(r":::figure\b(.*?)\n:::", raw, re.S | re.I):
        block = m.group(0)
        alt = " ".join(re.findall(r"^\s*alt:\s*(.+)$", block, re.M))
        cap = " ".join(re.findall(r"^\s*caption:\s*(.+)$", block, re.M))
        slug = " ".join(re.findall(r"slug=([\w-]+)", block))
        if SHOT_ALT_HINT.search(alt) or SHOT_ALT_HINT.search(cap):
            found.append(("скрин", _short((alt or cap), 90)))
            continue
        if set(re.split(r"[^a-z0-9]+", slug.lower())) & SHOT_SRC_TOKENS:
            found.append(("скрин", f"slug={slug}"))
    for m in re.finditer(r":::pre\b.*?\n:::", raw, re.S | re.I):
        inner = m.group(0)
        if SHELL_CMD.search(inner) or SHELL_PROMPT.search(inner):
            found.append(("мокап терминала", _short(inner.strip(), 90)))
    return found


