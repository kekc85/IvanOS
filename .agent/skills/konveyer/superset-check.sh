#!/usr/bin/env bash
# superset-check.sh - машинная проверка контракта надмножества скилла konveyer.
#
# Что проверяет:
#   1) якорные блоки - в SKILL.md обязан присутствовать каждый блок методологии
#      автономной оркестрации (поиск дословной фразы-якоря, grep -F, регистр как записан).
#      Якорь ТЕЛЕСНЫЙ: фраза стоит в ТЕЛЕ своего блока и в чужом блоке не встречается,
#      а ссылка на блок её не содержит. Поэтому полноэкранный поиск не даёт ложного
#      зелёного от упоминания блока в оглавлении или в соседнем разделе;
#   2) негативные якоря - специфика владельца (личное имя и личный домен, дословный список
#      держит литерал OWNER_RE ниже и только он: в комментарии эти слова не повторяются,
#      иначе сам файл становится утечкой и уезжает ученику вместе с раздачей). В РАЗДАВАЕМОЙ
#      копии (кит, dist, любой путь кроме живого дефолта) это расхождение: личное владельца
#      уезжает ученику. На живом дефолте это норма и печатается справкой;
#   3) дрейф канона - применим ТОЛЬКО когда судится живой файл владельца. Тогда sha256 канона
#      сверяется с зафиксированным при последней сверке надмножества (canon.sha256 рядом с
#      ЖИВЫМ SKILL.md). Канон правлен, а скилл нет = расхождение. Провал ЗАПИСИ хэша тоже
#      расхождение: тихого самовосстановления в этом месте быть не должно. Для раздаваемой
#      копии дрейф не судится и НИКАКИЕ файлы рядом с ней не создаются: канона у получателя
#      нет по построению, а хэш-файл, положенный рядом с копией, засоряет саму копию.
#
# Зачем: скилл раздаётся, канон нет. Пробел скилла у владельца замаскирован,
# у получателя виден во всей красе. Контракт держится кодом, а не вниманием.
#
# Вход:  $1 - путь к SKILL.md. По умолчанию - SKILL.md РЯДОМ СО СКРИПТОМ (самолокация):
#        живой скрипт судит живой файл, скрипт внутри копии судит СВОЮ копию. Голый прогон
#        из папки кита больше не подсовывает себе живой файл владельца и не даёт
#        дистрибьютору ложного зелёного на непроверенной копии.
#        --platform claude|codex - под какую раздачу судить (дефолт claude, обратная
#        совместимость: старая форма вызова без флага работает как раньше).
#        --anchors - самоотчёт по составу якорей (числа берутся из самих массивов).
# Выход: строка на каждый блок (OK / FAIL), затем строка "ИТОГ: расхождений N"
# Коды:  0 - расхождений нет; 1 - есть хотя бы одно
#
# Живой или раздаваемая копия - решается ОДНИМ сравнением абсолютных путей субъекта с живым
# дефолтом. От него зависят обе развилки: негативные якоря и дрейф-проверка.
#
# Деградация объявленная, не молчаливая: нет канона на машине либо судится копия - печатается
# строка про пропуск дрейф-проверки, и это НЕ считается расхождением.

set -uo pipefail

# ── разбор аргументов ────────────────────────────────────────────────────────
# Обратная совместимость обязательна: голый прогон и прогон с одним позиционным путём
# ведут себя ровно как до ввода классов якорей. Платформа влияет ТОЛЬКО на три якоря,
# которые называют инструмент или уровень модели конкретной среды.
PLATFORM="claude"
ANCHORS_ONLY=0
SKILL=""
while [ "$#" -gt 0 ]; do
  case "$1" in
    --platform)
      PLATFORM="${2:-}"
      shift 2 || shift
      ;;
    --platform=*)
      PLATFORM="${1#--platform=}"
      shift
      ;;
    --anchors)
      ANCHORS_ONLY=1
      shift
      ;;
    *)
      [ -z "$SKILL" ] && SKILL="$1"
      shift
      ;;
  esac
done
case "$PLATFORM" in
  claude|codex) ;;
  *)
    echo "FAIL аргумент: --platform принимает claude или codex, получено '$PLATFORM'"
    echo "ИТОГ: расхождений 1"
    exit 1
    ;;
esac
[ -z "$SKILL" ] && SKILL="$(dirname "$0")/SKILL.md"
DEFAULT_SKILL="$HOME/.claude/skills/konveyer/SKILL.md"
CANON="$HOME/.business/processes/autonomous-orchestration-prompt.md"
# Хэш канона живёт рядом с ЖИВЫМ SKILL.md, а не рядом со скриптом: читается и пишется он
# только на живом субъекте, и якорь на живую папку страхует от файла-мусора в копии даже
# тогда, когда живой файл судят скриптом из копии.
HASHFILE="$(dirname "$DEFAULT_SKILL")/canon.sha256"

DIFF=0

abspath() {
  local p="$1" d b
  b="$(basename "$p")"
  d="$(cd "$(dirname "$p")" 2>/dev/null && pwd -P)"
  if [ -n "$d" ]; then
    printf '%s/%s\n' "$d" "$b"
  else
    printf '%s\n' "$p"
  fi
}

# ── два класса якорей ────────────────────────────────────────────────────────
# НЕЙТРАЛЬНЫЕ якоря судятся одинаково в любой раздаче: они называют закон режима, а не
# инструмент среды. Формат записи: "имя блока|якорная фраза". Якорь берётся из ТЕЛА блока,
# не из его заголовка и не из ссылки на него: заголовок и ссылка повторяются по файлу, тело - нет.
BLOCKS_NEUTRAL=(
  "вопросы-развилки|Вопросов-развилок"
  "три случая спросить|действие в проде"
  "критика ТЗ до исполнения|1k-kritika-tz.md"
  "оси готового|минимум шесть осей готового"
  "панель критиков|своим файлом вердикта"
  "гейт по типу артефакта|Чужой гейт даёт красивый зелёный отчёт мимо предмета"
  "текст через humaniser|скилл humaniser"
  "код через security|три независимых security-прохода"
  "скан секретов|скан секретов"
  "регресс|Повтор ошибки, которая уже ловилась раньше"
  "границы прода|Не деплоишь, не пушишь в прод"
  "ночной прогон|caffeinate"
  "открываемый показ|в открываемом виде"
  "сам чекер|superset-check.sh"
  "маршрут финала|Конвейер: аналитик"
  "счётчик реестра|хвостов открытых:"
  "стоп-критерий|без НОВЫХ дефектов severity blocker и major"
  "контракт нуля|Пустое решение и любое четвёртое значение"
  "свежесть улик|evidence-freshness.sh"
  "лимит без ожидания|не жди сброса"
  "тотал-ревью|как было / как стало"
  "точка возврата|где встал"
  "входной ассет|входном ассете"
  "перепроверка находок|перепроверяй сам живьём"
  "реестр критериев|Реестр критериев, судящих живой артефакт по имени"
  "целесообразность круга|этот круг автоматически последний"
  "зона дефекта|зона ПРОДУКТ или УЧЁТ"
)

# ПЛАТФОРМЕННЫЕ якоря называют инструмент фан-аута, минимальный уровень модели и правило
# версий - то есть ровно то, что у сред разное. Нейтральная переформулировка стёрла бы
# конкретику, ради которой якорь и стоит, и чекер перестал бы ловить подмену платформенного
# куска. Поэтому у каждого такого якоря ПАРА литералов.
# Формат записи: "имя блока|claude-литерал|codex-литерал".
BLOCKS_PLATFORM=(
  "fan-out|Workflow-оркестратор|spawn_agent"
  "экономика моделей|суждение НИКОГДА не опускается ниже opus|суждение НИКОГДА не опускается ниже старшей модели твоего плана"
  "версии моделей|только актуальные пятые|только актуальные слаги из codex debug models"
)

if [ "$ANCHORS_ONLY" -eq 1 ]; then
  echo "нейтральных якорей: ${#BLOCKS_NEUTRAL[@]}"
  echo "платформенных якорей: ${#BLOCKS_PLATFORM[@]}"
  echo "всего якорей: $(( ${#BLOCKS_NEUTRAL[@]} + ${#BLOCKS_PLATFORM[@]} ))"
  exit 0
fi

if [ ! -f "$SKILL" ]; then
  echo "FAIL файл скилла: не найден путь $SKILL"
  echo "ИТОГ: расхождений 1"
  exit 1
fi

# Живой файл владельца или раздаваемая копия. Сравниваются абсолютные пути СУБЪЕКТА и живого
# дефолта, а не путь скрипта: одно значение обслуживает обе развилки ниже, поэтому негативные
# якоря и дрейф-проверка не могут разойтись в том, что именно сейчас судится.
IS_LIVE=0
if [ "$(abspath "$SKILL")" = "$(abspath "$DEFAULT_SKILL")" ]; then
  IS_LIVE=1
fi

echo "платформа: $PLATFORM"

for entry in "${BLOCKS_NEUTRAL[@]}"; do
  name="${entry%%|*}"
  anchor="${entry#*|}"
  if grep -Fq -- "$anchor" "$SKILL"; then
    echo "OK $name"
  else
    echo "FAIL $name: якорь '$anchor' не найден"
    DIFF=$((DIFF + 1))
  fi
done

for entry in "${BLOCKS_PLATFORM[@]}"; do
  name="${entry%%|*}"
  rest="${entry#*|}"
  if [ "$PLATFORM" = "codex" ]; then
    anchor="${rest#*|}"
  else
    anchor="${rest%%|*}"
  fi
  if grep -Fq -- "$anchor" "$SKILL"; then
    echo "OK $name (платформенный, $PLATFORM)"
  else
    echo "FAIL $name (платформенный, $PLATFORM): якорь '$anchor' не найден"
    DIFF=$((DIFF + 1))
  fi
done

# ── негативные якоря: специфика владельца в раздаваемой копии ────────────────
# Судим по ПУТИ. Живой дефолт - рабочий файл владельца, личное в нём законно.
# Любой другой путь (кит, dist, копия в архиве) раздаётся дальше как есть.
# Литерал разорван кавычками НАМЕРЕННО: скраб-скрипты пересборки дистрибутива делают
# литеральную замену имени владельца по всем файлам и убивали регулярку детектора.
# Разрыв невидим для литеральной замены, рантайм склеивает строку обратно
OWNER_RE='Ив''ан|theivan''sergeev'
OWN_N="$(grep -c -E -- "$OWNER_RE" "$SKILL" 2>/dev/null || true)"
OWN_N="${OWN_N:-0}"

if [ "$IS_LIVE" -eq 1 ]; then
  echo "специфика владельца: $OWN_N строк (норма для живого файла)"
elif [ "$OWN_N" -gt 0 ]; then
  echo "FAIL специфика владельца в раздаваемой копии: $OWN_N строк с личным владельца - раздаваемый артефакт не должен его нести"
  grep -n -E -- "$OWNER_RE" "$SKILL" 2>/dev/null | head -3 | while IFS=: read -r ln rest; do
    printf '    %s:%s  %s\n' "$SKILL" "$ln" "$(printf '%s' "$rest" | cut -c1-70)"
  done
  DIFF=$((DIFF + 1))
else
  echo "OK специфика владельца: 0 строк в раздаваемой копии"
fi

sha_of() {
  if command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$1" 2>/dev/null | awk '{print $1}'
  elif command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" 2>/dev/null | awk '{print $1}'
  else
    echo ""
  fi
}

if [ "$IS_LIVE" -ne 1 ]; then
  # Копия судится только по якорям. Ни чтения, ни записи canon.sha256: канона у получателя
  # нет, а созданный рядом с копией хэш-файл уехал бы в кит вместе с ней.
  echo "дрейф канона: применим только к живому файлу, пропущен"
elif [ -f "$CANON" ]; then
  CUR="$(sha_of "$CANON")"
  if [ -z "$CUR" ]; then
    echo "дрейф-проверка пропущена: не найден ни shasum, ни sha256sum"
  elif [ ! -f "$HASHFILE" ]; then
    # Запись первого хэша обязана быть проверена: каталог скилла бывает только для чтения,
    # и молча продолженный прогон означал бы вечно новую «первую фиксацию» без дрейф-проверки.
    if printf '%s\n' "$CUR" > "$HASHFILE" 2>/dev/null &&
       [ "$(tr -d ' \t\r\n' < "$HASHFILE" 2>/dev/null)" = "$CUR" ]; then
      echo "канон-хэш зафиксирован впервые"
    else
      echo "FAIL: хэш канона не записался в $HASHFILE"
      DIFF=$((DIFF + 1))
    fi
  else
    PREV="$(tr -d ' \t\r\n' < "$HASHFILE")"
    if [ "$PREV" != "$CUR" ]; then
      echo "FAIL дрейф канона: канон правлен после последней сверки надмножества - перенеси новое в SKILL.md и обнови canon.sha256 (одной строкой: пересчитай и перезапиши)"
      DIFF=$((DIFF + 1))
    else
      echo "OK дрейф канона"
    fi
  fi
else
  echo "канон не найден: дрейф-проверка применима только на машине владельца, пропущена"
fi

echo "ИТОГ: расхождений $DIFF"

if [ "$DIFF" -eq 0 ]; then
  exit 0
fi
exit 1

# ── ТЕСТЫ (ручные) ──
# happy:    bash ~/.claude/skills/konveyer/superset-check.sh  → строки OK, "ИТОГ: расхождений 0", exit=0
# классы:   bash superset-check.sh --anchors                  → "нейтральных якорей: 25",
#           "платформенных якорей: 3", "всего якорей: 28", exit=0
# codex:    bash superset-check.sh --platform codex <codex-кит>/skills/konveyer/SKILL.md
#           → три платформенных якоря судятся codex-литералами, "ИТОГ: расхождений 0"
# кросс:    bash superset-check.sh --platform codex <claude SKILL.md> → "ИТОГ: расхождений 3"
#           (классы правда разные, а не декоративные)
# аргумент: bash superset-check.sh --platform windows            → FAIL аргумент, exit=1
# negative: bash superset-check.sh /tmp/pustoy.md        → FAIL по каждому якорю, exit=1
# edge:     bash superset-check.sh /tmp/net-takogo.md    → FAIL файл скилла, exit=1
# копия:    bash superset-check.sh <кит>/skills/konveyer/SKILL.md → судится САМА копия, включаются
#           негативные якоря (специфика владельца = расхождение, а не справка)
# самолок.: cd <кит>/skills/konveyer && bash superset-check.sh → БЕЗ аргумента судится SKILL.md
#           рядом со скриптом, то есть копия; печатается "дрейф канона: применим только
#           к живому файлу, пропущен", файл canon.sha256 в папке копии НЕ появляется
# дрейф:    правка канона без правки скилла              → FAIL дрейф канона, exit=1
# хэш:      chmod a-w папка скилла, canon.sha256 переименовать в canon.sha256.bak (не удалять)  → FAIL: хэш канона не записался, exit=1
# обнов:    shasum -a 256 "$HOME/.business/processes/autonomous-orchestration-prompt.md" | awk '{print $1}' > "$HOME/.claude/skills/konveyer/canon.sha256"
