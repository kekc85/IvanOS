"""TTS-текст-линт + РЕЕСТР ПРОИЗНОШЕНИЙ перед озвучкой (Гейт Озвучки, шаг 1 — Фаза 4).

Прецедент по решению автора (facerating-reel): «Чат Джи Пи Ти» кириллицей + кривые ударения
ушли в готовый ролик. Прецедент по решению автора (<твой-прошлый-проект>): HeyGen-TTS читает англицизм
«Lovable» как «ловАбл» вместо «ловЭбл» — кривое ударение латиницы.

РЕШЕНИЕ (системное): движок НЕ поддерживает метки ударения → единственный рычаг =
ВХОДНОЙ ТЕКСТ. Каждый проблемный англицизм решается ОДИН раз подобранным кириллическим
написанием (звучит верным ударением) и заносится в PRONUNCIATION_MAP ниже. Дальше:
  - линт FAIL, если в TTS-тексте есть СЫРОЙ англицизм из реестра (латиницей) — машина
    не пускает текст в генерацию, пока он не переписан на проверенное написание.
  - `--apply` печатает текст с авто-подстановкой написаний из реестра (то, что уходит в HeyGen).
Написание проверяется УХОМ один раз на коротком рендере (Ф4 шаг 3) → verified.

FAIL (exit 2): сырой англицизм из реестра в тексте · кириллический транслит из чёрного списка.
WARN (exit 0): цифры (надёжнее прописью) · частотные омографы.

Usage:
  tts-textlint.py "<text>"  |  tts-textlint.py --file <path>     # линт
  tts-textlint.py --apply --file <path>                          # печать respell-текста для HeyGen
"""
import re
