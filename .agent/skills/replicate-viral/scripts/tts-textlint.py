# кириллические транслиты брендов, которые модель читает с кривым ударением (чёрный список)
BAD_TRANSLIT = [
    'джи пи ти', 'джи-пи-ти', 'джипити', 'чат гпт', 'чатгпт', 'чат-гпт',
    'хиггсфилд', 'хейген', 'эм би ти ай', 'эмбити', 'опенэйай', 'опен эй ай',
    'мидджорни', 'миджорни', 'юб тюб',
]

# частотные омографы, где не та позиция ударения ломает смысл/звучание
HOMOGRAPHS = [
    'замок', 'мука', 'орган', 'атлас', 'ирис', 'хлопок', 'парить', 'дорога',
    'берегу', 'стоит', 'пора', 'белки', 'кружки', 'гвоздики', 'полки',
]


def _term_re(term):
    # граница слова с учётом латиницы/кириллицы/цифр; регистронезависимо
    return re.compile(r'(?<![\wА-Яа-яЁё])' + re.escape(term) + r'(?![\wА-Яа-яЁё])', re.IGNORECASE)


def apply_registry(text: str) -> str:
    for term, respell in PRONUNCIATION_MAP.items():
        text = _term_re(term).sub(respell, text)
    return text


def lint(text: str) -> int:
    low = text.lower()
    fails, warns = [], []

    for term, respell in PRONUNCIATION_MAP.items():
        if _term_re(term).search(text):
            fails.append(f'сырой англицизм «{term}» в TTS-тексте — модель мажет ударение; '
                         f'перепиши на «{respell}» (реестр произношений) или прогони --apply')

    for b in BAD_TRANSLIT:
        if b in low:
            fails.append(f'транслит бренда кириллицей: «{b}» — пиши латиницей')

    for m in re.finditer(r'\d+', text):
        warns.append(f'цифра «{m.group(0)}» — надёжнее прописью в нужном падеже '
                     f'(модель может прочитать не в той форме)')

    for h in HOMOGRAPHS:
        if re.search(r'\b' + h + r'\b', low):
            warns.append(f'омограф «{h}» — ударение не контролируется, '
                         f'если можно — переформулируй')

    for w in warns:
        print(f'WARN (tts-textlint): {w}')
    if fails:
        for f in fails:
            print(f'FAIL (tts-textlint): {f}', file=sys.stderr)
        print('Память: feedback_tts_anglicisms_in_latin', file=sys.stderr)
        return 2
    if not warns:
        print('tts-textlint: PASS')
    return 0


if __name__ == '__main__':
    args = sys.argv[1:]
    do_apply = '--apply' in args
    if do_apply:
        args.remove('--apply')

    if len(args) >= 2 and args[0] == '--file':
        txt = open(args[1], encoding='utf-8').read()
    elif len(args) >= 1 and args[0] != '--file':
        txt = args[0]
    else:
        print('usage: tts-textlint.py "<text>" | --file <path> | --apply --file <path>',
              file=sys.stderr)
        sys.exit(1)

    if do_apply:
        sys.stdout.write(apply_registry(txt))
        sys.exit(0)
    sys.exit(lint(txt))