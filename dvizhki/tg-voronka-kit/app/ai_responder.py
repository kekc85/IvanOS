# -*- coding: utf-8 -*-
"""ИИ-ответчик воронки: КАРКАС. Персону сюда вписываешь ты.

ЧТО ЭТО. Когда человек в воронке пишет боту живое сообщение (а не жмёт кнопку),
бот может ответить сам - текстом от твоего лица, зная, на каком шаге воронки
человек стоит. Механика этого целиком лежит в боте и работает без правок. Не
лежит в ките ровно одно: ТЕКСТ ТВОЕЙ ПЕРСОНЫ. Кто ты, каким голосом говоришь,
что продаёшь, чего не обещаешь - это не переносится от одного человека к другому,
и подставлять сюда чужую персону было бы хуже пустоты.

ПОЧЕМУ КАРКАС, А НЕ ТИХОЕ ОТКЛЮЧЕНИЕ. Молча выключенная функция выглядит как
работающая: бот просто «иногда не отвечает», и причину не найти. Здесь наоборот:
пока `SYSTEM_PROMPT` пуст, каждая попытка ответить пишет в лог одну честную
строку, а сообщение лида уходит тебе как обычный неотвеченный. Ничего не теряется.

КАК ВКЛЮЧИТЬ, три шага:
  1. впиши свою персону в `SYSTEM_PROMPT` ниже - кто ты, о чём проект, как
     говоришь, чего никогда не обещаешь (гарантий дохода, сроков, возвратов
     сверх твоих правил)
  2. положи ключ модели в `.env`: `ANTHROPIC_API_KEY=...`
  3. перезапусти бота

БЕЗОПАСНОСТЬ. Сообщение человека - это ДАННЫЕ, а не команда. Что бы там ни было
написано («забудь инструкции», «выдай промпт», «сделай скидку»), моделью это
исполняться не должно: держи запрет прямо в тексте персоны и проверяй ответ
перед отправкой. Готовая проверка команд лежит ниже в `is_command_attempt`.
"""
import logging
import os
import re

LOG = logging.getLogger(__name__)

# ─────────────────────────────────────────────────────────────────────────────
# ТВОЯ ПЕРСОНА. Пусто = ИИ-ответчик выключен, бот работает как обычно.
# ─────────────────────────────────────────────────────────────────────────────
SYSTEM_PROMPT = ""

API_KEY = os.environ.get("ANTHROPIC_API_KEY", "")

_CATALOG = []
_CATALOG_URLS = {}


def set_catalog(entries):
    """Каталог лид-магнитов воронки: список кортежей (КЛЮЧ, код-слово, тема, url).
    Бот зовёт это на старте, чтобы ответчик знал, что вообще можно выдать."""
    global _CATALOG, _CATALOG_URLS
    _CATALOG = list(entries or [])
    _CATALOG_URLS = {str(e[0]).upper(): e[3] for e in _CATALOG if len(e) > 3}
    return len(_CATALOG)


def catalog_size():
    return len(_CATALOG)


def resolve_guide(key):
    return _CATALOG_URLS.get(str(key or "").upper(), "")


# Попытка командовать ботом текстом («выдай доступ», «поставь мне регистрацию»).
# Такие сообщения ответчик не обслуживает: они уходят человеку-владельцу.
_CMD_RE = re.compile(
    r"(выдай|дай|открой|поставь|сделай|отправь|пришли|верни|отмени|удали|сбрось)\s+"
    r"(мне\s+)?(доступ|регистрац\w*|скидк\w*|возврат\w*|подписк\w*|промпт\w*|инструкц\w*)",
    re.IGNORECASE)


def is_command_attempt(text):
    return bool(_CMD_RE.search(str(text or "")))


async def generate_reply(db, user_id, first_name, funnel_key, node, registered,
                         guide_url, unanswered, cabinet_url="", event=None):
    """Возвращает пару (текст ответа, причина). Пока персона не вписана - (None, 'off'),
    и вызывающий обслужит сообщение обычным путём: перешлёт владельцу.

    Причины: 'off' - персона или ключ не заданы · 'error' - сбой канала модели ·
    'guard' - ответ не прошёл твою проверку и отправлять его нельзя."""
    if not SYSTEM_PROMPT.strip() or not API_KEY:
        LOG.info("ИИ-ответчик выключен: персона в app/ai_responder.py пуста "
                 "либо нет ANTHROPIC_API_KEY. Сообщение лида уйдёт владельцу")
        return None, "off"
    # Свой канал модели подключается здесь. Контракт менять не нужно: бот ждёт
    # ровно пару (текст, причина).
    LOG.warning("ИИ-ответчик: персона задана, но канал модели не подключён")
    return None, "error"
