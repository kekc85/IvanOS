#!/usr/bin/env python3
"""
Дизайн-система карусели для auto-uniqualize.

Решает 4 зоны роста уникализации (фидбэк автора):

  ЗОНА 1 — Дизайн-консистентность. Один визуальный язык на всю карусель
           (палитра / фон / типографика) + ОДНА фирменная «фишка». Внутри
           карусели всё консистентно (бренд узнаётся), между каруселями
           «фишка» и палитра меняются (удивляем новым приёмом, не хаосом).
  ЗОНА 2 — Последний слайд (CTA). Шаблон с моком ТЕЛЕГРАМ-КАНАЛА автора
           вместо чужого бренда. Параметризуемый.
  ЗОНА 3 — Pre-flight чеклист лиц. Бинарное решение «менять лицо у ВСЕХ /
           ни у кого / только автор» на всю карусель, без выборочности.
  ЗОНА 4 — Умные промпты. Полная схема промпта на каждый слайд:
           мой текст + design-tokens + решение по лицам + фишка + правила.

Модуль чистый (без Playwright), импортируется в driver.py. Без файлов
`_design.*` / `_faces.txt` всё работает как раньше (обратная совместимость).
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path


# ============================================================
# ЗОНА 1 — Дизайн-профиль карусели (единый визуальный язык)
# ============================================================


@dataclass
class CarouselDesignProfile:
    """Единый визуальный язык одной карусели.

    Кладётся в пакет как `_design.json` (приоритет) или `_design.txt`
    (свободный текст одной строкой/абзацем = сразу идёт в промпт как есть).
    Применяется в промпт КАЖДОГО слайда → слайды внутри карусели
    консистентны (палитра/фон/типографика/фишка одни на всех).

    Поля:
      palette      — 2-4 hex-цвета фирменной палитры карусели.
      palette_role — словами роль цветов (что фон, что акцент, что текст).
      background   — тип фона (напр. «тёмный графит с зернистостью»,
                     «кремовый бумажный», «сетка-grid на тёмном»).
      typography   — описание типографики (гарнитура по характеру, вес,
                     размер заголовка vs тело, без конкретного имени шрифта).
      signature    — фирменная «фишка» карусели: ОДИН приём, который цепляет,
                     но не отвлекает. Эффект / намёк на motion / UI-приём /
                     тип фона. Один на всю карусель, меняется между каруселями.
      mood         — общее настроение (премиальное / дерзкое / тёплое...).
      notes        — доп. ограничения свободным текстом (опционально).
    """

    palette: list[str] = field(default_factory=list)
    palette_role: str = ""
    background: str = ""
    typography: str = ""
    signature: str = ""
    mood: str = ""
    notes: str = ""
    raw: str = ""  # если профиль задан свободным текстом (_design.txt)

    def is_empty(self) -> bool:
        return not any(
            [self.palette, self.palette_role, self.background, self.typography,
             self.signature, self.mood, self.notes, self.raw]
        )

    def to_prompt_block(self) -> str:
        """Собирает блок design-tokens для вставки в промпт слайда.

        Возвращает пустую строку если профиль не задан — тогда промпт
        работает в старом режиме (обратная совместимость).
        """
        if self.is_empty():
            return ""
        if self.raw:
            return ("ЕДИНЫЙ СТИЛЬ СЕРИИ (на всех слайдах одинаково):\n"
                    + self.raw.strip()[:600])
        lines = ["ЕДИНЫЙ СТИЛЬ НА ВСЕХ СЛАЙДАХ (один бренд, цвета и приём не "
                 "меняй от слайда к слайду):"]
        if self.palette:
            role = f" — {self.palette_role[:120]}" if self.palette_role else ""
            lines.append(f"- Палитра: {', '.join(self.palette)[:160]}{role}.")
        elif self.palette_role:
            lines.append(f"- Цвета: {self.palette_role[:160]}.")
        if self.background:
            lines.append(f"- Фон: {self.background[:140]}.")
        if self.typography:
            lines.append(f"- Шрифты: {self.typography[:140]}.")
        if self.signature:
            lines.append(f"- Фишка серии: {self.signature[:140]} "
                         "(повторяется на каждом слайде, не перетягивает внимание).")
        return "\n".join(lines)


def load_design_profile(package_dir: Path) -> CarouselDesignProfile:
    """Читает дизайн-профиль карусели из пакета.

    Приоритет: `_design.json` → `_design.txt` → пустой профиль.
    Пустой профиль = старое поведение (обратная совместимость).
    """
    json_path = package_dir / "_design.json"
    if json_path.exists():
        try:
            data = json.loads(json_path.read_text(encoding="utf-8"))
            return CarouselDesignProfile(
                palette=list(data.get("palette", []) or []),
                palette_role=str(data.get("palette_role", "") or ""),
                background=str(data.get("background", "") or ""),
                typography=str(data.get("typography", "") or ""),
                signature=str(data.get("signature", "") or ""),
                mood=str(data.get("mood", "") or ""),
                notes=str(data.get("notes", "") or ""),
            )
        except Exception:
            # битый JSON — не валим прогон, работаем без профиля
            return CarouselDesignProfile()
    txt_path = package_dir / "_design.txt"
    if txt_path.exists():
        raw = txt_path.read_text(encoding="utf-8").strip()
        if raw:
            return CarouselDesignProfile(raw=raw)
    return CarouselDesignProfile()


# ============================================================
# ЗОНА 3 — Pre-flight чеклист лиц (бинарное решение на карусель)
# ============================================================

# Допустимые значения face-policy:
#   "none"        — лицо не менять ни на одном слайде.
#   "all"         — заменить лицо на всех слайдах, где лицо вообще есть.
#   "author-only" — заменить ТОЛЬКО лицо автора контента, героев/известных
#                   оставить (семантику различает кастомка через промпт).
FACE_POLICIES = ("none", "all", "author-only")
DEFAULT_FACE_POLICY = "author-only"


@dataclass
class FaceDecision:
    """Решение по лицам на всю карусель (бинарно-консистентное).

    policy задаётся файлом пакета `_faces.txt` (одно слово). Claude в сессии
    ПЕРЕД прогоном смотрит все слайды и пишет туда явное решение. Если файла
    нет — fallback на DEFAULT_FACE_POLICY ("author-only" = старое поведение).
    """

    policy: str = DEFAULT_FACE_POLICY
    explicit: bool = False  # True если решение задано файлом, False = дефолт

    def swap_anywhere(self) -> bool:
        """Прикладываем ли лицо автора хоть к каким-то слайдам."""
        return self.policy in ("all", "author-only")


def load_face_decision(package_dir: Path) -> FaceDecision:
    """Читает `_faces.txt` (одно слово: none | all | author-only)."""
    p = package_dir / "_faces.txt"
    if p.exists():
        val = p.read_text(encoding="utf-8").strip().lower()
        # допускаем мелкие вариации записи
        val = val.split()[0] if val else ""
        if val in FACE_POLICIES:
            return FaceDecision(policy=val, explicit=True)
    return FaceDecision(policy=DEFAULT_FACE_POLICY, explicit=False)


def preflight_face_checklist(images: list[Path], has_face_fn) -> dict:
    """Pre-flight анализ всей карусели по лицам ДО прогона.

    Возвращает сводку (для лога), на основе которой Claude/человек принимает
    бинарное решение. Сам по себе детектор не решает «автор или герой» —
    это семантика, её ставит Claude через `_faces.txt`. Эта функция даёт
    объективный сигнал: на скольких слайдах opencv видит лицо.

      images      — список путей слайдов в порядке карусели.
      has_face_fn — функция has_face(path) -> bool из driver.

    Возврат:
      {
        "total": N,
        "slides_with_face": [индексы 1-based],
        "face_count": сколько слайдов с лицом,
        "suggestion": рекомендуемая policy ("none" если лиц нет),
      }
    """
    with_face = []
    for idx, img in enumerate(images, start=1):
        try:
            if has_face_fn(img):
                with_face.append(idx)
        except Exception:
            pass
    suggestion = "none" if not with_face else DEFAULT_FACE_POLICY
    return {
        "total": len(images),
        "slides_with_face": with_face,
        "face_count": len(with_face),
        "suggestion": suggestion,
    }


def face_instruction(policy: str, face_in_frame: bool) -> str:
    """Кусок промпта про лицо для конкретного слайда — консистентно с policy.

    Бинарность гарантируется тем, что на ВСЕ слайды одной карусели приходит
    один и тот же policy. Никакой выборочности «у этого заменю, у того нет»
    по наитию кастомки — поведение фиксировано решением на карусель.
    """
    if policy == "none":
        # лицо не трогаем нигде — явно запрещаем замену
        return ("Лица на слайде НЕ заменяй и новых людей не добавляй, "
                "оставь как в оригинале. ")
    if not face_in_frame:
        # на этом слайде лица нет — но policy «менять» относится ко всей серии
        return ""
    if policy == "all":
        return ("На этом слайде есть человек. Замени ЕГО лицо на моё со второго "
                "фото, фотореалистично и узнаваемо. Делай это консистентно со "
                "всеми слайдами серии, где есть люди — один и тот же человек "
                "(я) на всех. Новых людей не добавляй. ")
    # author-only (дефолт)
    return ("На этом слайде есть человек. ТОЛЬКО если это АВТОР контента "
            "(крупный портрет блогера, селфи, говорящая голова создателя) — "
            "замени его лицо на моё со второго фото, фотореалистично и "
            "узнаваемо, консистентно на всех таких слайдах серии. Если это "
            "известная личность, герой новости или человек по теме контента — "
            "НЕ трогай, оставь оригинальное лицо. Новых людей не добавляй. ")


# ============================================================
# Общие правила уникализации (зашиты в каждый промпт) — ЗОНА 4
# ============================================================

# Правила, которые автор накопил по прецедентам. Зашиваются в промпт-builder,
# а не держатся «в голове» кастомки.
UNIQ_RULES = (
    "ПРАВИЛА (МИРРОР, НЕ РЕДИЗАЙН): сохрани изображение МАКСИМАЛЬНО близко к "
    "оригиналу - ту же композицию, раскладку, зоны, иерархию, фон, цвета, "
    "панели, иконки и иллюстрации, шрифтовую систему, ритм. Это уникализация "
    "зеркалированием: НЕ перерисовывай сцену заново, НЕ придумывай новый визуал, "
    "НЕ меняй макет. Измени РОВНО ДВЕ вещи: (1) текст - по моему переводу ниже; "
    "(2) убери ник и брендинг АВТОРА-ДОНОРА (@username донора, его подписи/"
    "водяные знаки/следы источника). Тематические логотипы и иконки, которые "
    "являются СОДЕРЖАНИЕМ слайда (напр. логотипы упоминаемых инструментов/"
    "сервисов), сохрани как в оригинале - это не бренд донора. "
    "Внутри строк дефис «-» или запятая, НЕ длинное тире. Мелкие служебные "
    "подписи в сложных досках/UI, не заданные в моём тексте, не выдумывай.\n"
)

# Правила перевода — для fallback-режима, когда текст переводит сама кастомка
# (нет slide-NN.txt). В режиме «мой текст» перевод не нужен.
TRANSLATE_RULES = (
    "ПЕРЕВОД ТЕКСТА (делаешь ты, т.к. готового текста к этому слайду нет):\n"
    "- ВЕСЬ текст переведи на русский, без английских вставок, единый язык на "
    "слайде.\n"
    "- Переводи по СМЫСЛУ и в контексте слайда, не дословной калькой с "
    "английского. Подбирай слова так, как реально говорят по-русски: если "
    "прямой перевод звучит чужеродно — найди естественный русский эквивалент.\n"
    "- Если на слайде сравнение или контраст (платный сервис против бесплатного "
    "инструмента, экономия) — передай его законченной мыслью со сказуемым и "
    "выводом, не обрывай фразу на полуслове.\n"
)


# ============================================================
# ЗОНА 4 — Промпт-builder (полная схема промпта на слайд)
# ============================================================


def build_slide_prompt(
    *,
    translation: str | None,
    design: CarouselDesignProfile,
    face_policy: str,
    face_in_frame: bool,
    with_face_attachment: bool,
    is_cta: bool = False,
    cta_mode: str = "codeword",  # "tg" = мок ТГ-канала; "codeword"/иное = чистый призыв без ТГ
    cta_topic: str = "",
    telegram_handle: str = "<твой-хэндл>",
) -> str:
    """Собирает ПОЛНЫЙ промпт одного слайда из всех слоёв.

    Слои (ЗОНА 4):
      1. что за вложения + базовая задача (рендер/уникализация);
      2. мой текст по зонам (если есть) ИЛИ правила перевода (fallback);
      3. design-tokens карусели (ЗОНА 1 — консистентность);
      4. решение по лицу для этого слайда (ЗОНА 3 — бинарно на серию);
      5. общие правила уникализации (бренды/em-dash/раскладка/мелкие подписи);
      6. для последнего слайда — CTA-шаблон с моком ТГ автора (ЗОНА 2).

    Возвращает один склеенный промпт-строку.
    """
    # Мок ТГ-канала — ТОЛЬКО если режим явно "tg" (на оригинале был телефон/экран
    # с чужим назначением, который заменяем). Иначе финальный слайд — обычный
    # призыв с код-словом (мой текст), БЕЗ телеграм-канала.
    if is_cta and cta_mode == "tg":
        return build_cta_prompt(
            translation=translation,
            design=design,
            face_policy=face_policy,
            face_in_frame=face_in_frame,
            with_face_attachment=with_face_attachment,
            cta_topic=cta_topic,
            telegram_handle=telegram_handle,
        )

    parts: list[str] = []

    # 1. Вводная: что за вложения.
    if with_face_attachment:
        parts.append(
            "Первое вложение — слайд-оригинал карусели для уникализации. "
            "Второе вложение — это я, моё лицо (для возможной замены)."
        )
    else:
        parts.append("Вложение — слайд-оригинал карусели для уникализации.")

    # 2. Текст: мой готовый (приоритет) или правила перевода (fallback).
    if translation:
        parts.append(
            "ТЕКСТ НА СЛАЙДЕ — РОВНО ЭТОТ, не переводи, не меняй, не добавляй "
            "и не сокращай. Отрисуй точь-в-точь по зонам как написано ниже, "
            "весь остальной текст с оригинала убери:\n\n" + translation.strip()
        )
    else:
        parts.append(TRANSLATE_RULES.strip())

    # 3. Design-tokens (ЗОНА 1). Пусто если профиля нет → старое поведение.
    design_block = design.to_prompt_block()
    if design_block:
        parts.append(design_block)

    # 4. Лицо (ЗОНА 3).
    face_block = face_instruction(face_policy, face_in_frame)
    if face_block.strip():
        parts.append(face_block.strip())

    # 5. Общие правила уникализации.
    parts.append(UNIQ_RULES.strip())

    # 5.5. CTA-слайд без ТГ (режим codeword): чистый призыв + УЛЬТРА-РЕАЛИСТИЧНЫЙ
    # вид/содержание магнита ИЛИ результата. БЕЗ мокапа Telegram-канала (правило по решению автора).
    # Режим "mirror" (по решению автора): финальный слайд ЗЕРКАЛИТСЯ с закрывающего слайда
    # донора (та же раскладка), меняется только текст на наш призыв+код-слово - НЕ
    # перерисовываем магнит. Тогда весь набор остаётся мирором оригинала.
    if is_cta and cta_mode not in ("tg", "mirror"):
        topic = cta_topic.strip()
        parts.append(
            "ЭТО ФИНАЛЬНЫЙ CTA-СЛАЙД. НЕ рисовать мокап Telegram-канала, НЕ рисовать телефон/мессенджер. "
            "Composition: крупный чистый призыв с кодовым словом (как в тексте по зонам) + "
            "УЛЬТРА-РЕАЛИСТИЧНЫЙ визуал того, ЧТО человек получит, по теме карусели: "
            "либо вид/содержание самого магнита (обложка и страницы гайда/PDF, реалистичный документ), "
            "либо РЕЗУЛЬТАТ, который даёт магнит (реалистичный скрин/кадр итога). "
            + (f"Тема выдачи: {topic}. " if topic else "")
            + "Фотореалистично и дорого, без абстрактных плашек и стоковых иконок, в стиле серии. "
            "Чужих брендов/ников не оставлять."
        )

    # 6. Финал. ЖЁСТКО (по решению автора): кастомка ломала кадр (4:5 → 9:14) и рисовала
    # с нуля по контексту прошлого чата вместо трансформации вложенного оригинала.
    parts.append(
        "ЖЁСТКИЕ ТРЕБОВАНИЯ К ВЫВОДУ:\n"
        "1) Работай ТОЛЬКО с приложенным изображением этого сообщения. "
        "ИГНОРИРУЙ любые слайды, описания и задачи из прошлых чатов - "
        "рисовать заново по памяти ЗАПРЕЩЕНО.\n"
        "2) СООТНОШЕНИЕ СТОРОН результата обязано совпасть с приложенным оригиналом "
        "(вертикальный кадр 4:5). Не вытягивай и не обрезай кадр.\n"
        "3) Композиция, объекты, фон и цвета - как в оригинале. "
        "Меняется только текст и брендинг донора.\n"
        "Верни одну готовую картинку."
    )

    return "\n\n".join(parts)


# ============================================================
# ЗОНА 2 — CTA-шаблон (мок телеграм-канала автора)
# ============================================================


def build_cta_prompt(
    *,
    translation: str | None,
    design: CarouselDesignProfile,
    face_policy: str,
    face_in_frame: bool,
    with_face_attachment: bool,
    cta_topic: str = "",
    telegram_handle: str = "<твой-хэндл>",
) -> str:
    """Промпт последнего слайда (CTA) с моком ТЕЛЕГРАМ-КАНАЛА автора.

    Заменяет чужой бренд в мокапе телефона (например «bestapps.ai») на пост
    автора по теме карусели с большим числом реакций → путь клиента «в телеграм»
    становится очевидным.

    Подача варьируется (где-то мок телефона не подойдёт): если в `_design.txt`
    или notes задано иное — кастомка адаптирует. Здесь даём основной паттерн.
    """
    parts: list[str] = []

    if with_face_attachment:
        parts.append(
            "Первое вложение — финальный слайд карусели (призыв к действию). "
            "Второе вложение — это я, моё лицо."
        )
    else:
        parts.append("Вложение — финальный слайд карусели (призыв к действию).")

    # Текст CTA: мой готовый или правила перевода.
    if translation:
        parts.append(
            "ТЕКСТ НА СЛАЙДЕ — РОВНО ЭТОТ, не переводи и не меняй, отрисуй по "
            "зонам как написано, остальной текст оригинала убери:\n\n"
            + translation.strip()
        )
    else:
        parts.append(TRANSLATE_RULES.strip())

    topic_line = (
        f" Тема поста на экране — по сути этой карусели: {cta_topic.strip()}."
        if cta_topic.strip()
        else " Тема поста на экране — по сути этой карусели (тот же оффер, что в серии)."
    )

    # CTA-мок ТГ-канала + скриншот-референс (компактно — длинный промпт ChatGPT
    # конвертит в файл-вложение и не отправляет).
    parts.append(
        "ЭТО CTA-СЛАЙД. Оформи мок МОЕГО телеграм-канала "
        f"{telegram_handle}." + topic_line + " "
        "ПРЕДПОСЛЕДНЕЕ вложение — реальный скриншот моего канала: повтори его "
        "стиль ТОЧНО (название «автор Официальный», 26 986 подписчиков, "
        "синий бейдж «A+», зелёные обои Telegram, телеграмный вид поста). "
        "🔴 ПОСЛЕДНЕЕ вложение — моё реальное лицо (фото): вставь ЕГО в круглый "
        "аватар канала ОДИН-В-ОДИН как фотографию (crop в круг), НЕ перерисовывай "
        "лицо, НЕ генери другого человека, НЕ стилизуй — лицо точь-в-точь как на фото. "
        "Метрики реалистичные (десятки-сотни реакций, НЕ накручивай 249к). Чужих "
        "брендов и ников не оставляй."
    )

    # Design-tokens — CTA в том же стиле, что вся серия.
    design_block = design.to_prompt_block()
    if design_block:
        parts.append(design_block)

    # Лицо.
    face_block = face_instruction(face_policy, face_in_frame)
    if face_block.strip():
        parts.append(face_block.strip())

    # Общие правила.
    parts.append(UNIQ_RULES.strip())

    parts.append("Верни одну готовую картинку.")

    return "\n\n".join(parts)


def is_last_slide(idx: int, total: int) -> bool:
    """Последний слайд карусели = кандидат на CTA-шаблон."""
    return idx == total and total > 1
